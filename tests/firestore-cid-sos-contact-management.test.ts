import assert from 'node:assert/strict';
import {test,after} from 'node:test';
import {randomBytes,createHash} from 'node:crypto';
import {initializeApp,getApps,deleteApp} from 'firebase-admin/app';
import {getFirestore} from 'firebase-admin/firestore';
import {assertCidSosEmulator,CID_EMULATOR_PROJECT,createCidSosEmulatorStore} from '../server/identity/cidSosEmulatorStore';
import {CID_CHAT_EMULATOR_ORIGIN as origin,createCidChatEmulatorStore} from '../server/identity/cidChatEmulatorStore';
import {createCidOwnerCentralEmulator} from '../server/identity/cidOwnerCentralEmulator';
import {prepareCidSosConfig,type ChannelGrant} from '../server/identity/cidSosPrivateConfig';
import {isolatedTagPasskeyScope,issueTagPasskeyChallenge} from '../server/identity/kyrubTagPasskeyPolicy';
import {tagRegistrationOptions,verifyTagRegistration} from '../server/identity/kyrubTagPasskeyVerifier';
import {makeSoftwareTagAuthenticator} from './fixtures/kyrub-tag-software-authenticator';
assertCidSosEmulator();
const app=initializeApp({projectId:CID_EMULATOR_PROJECT},'cid-central-fixtures');
const db=getFirestore(app),now=Date.UTC(2026,10,26,12),tagId='a'.repeat(32),ownerId='owner-test',id='b'.repeat(32);
const tag={tagId,ownerId,displayName:'CID fictício',active:true};
const root=db.collection('cid_sos_emulator_tags').doc(tagId);
const person=(id:string)=>({id,name:id,channels:[{channel:'email',address:id+'@example.invalid'}]});
const config=prepareCidSosConfig(tag,ownerId,null,{expectedRevision:0,enabled:true,owner:person(ownerId),contacts:[person('contact-test')]});
const grants:ChannelGrant[]=[config.owner,...config.contacts].flatMap(p=>p.channels.map(c=>({...c,tagId,ownerId,participantId:p.id,verifiedAt:now-1000,consent:true})));
const hash=(s:string)=>createHash('sha256').update(s).digest('hex');
after(async()=>{for(const a of getApps().filter(a=>['cid-central-fixtures','cid-sos-local-emulator','cid-chat-local-emulator','cid-owner-central-local-emulator'].includes(a.name)))await deleteApp(a);});
test('fresh signed config changes, independent channel consent and revocation',async()=>{
 await root.set({tag,revision:0});
 const configRef=root.collection('private').doc('config'),grantRef=root.collection('private').doc('grants');
 await configRef.set({config});await grantRef.set({grants});
 const scope=isolatedTagPasskeyScope(origin,origin),auth=makeSoftwareTagAuthenticator(origin,scope.rpId);
 const reg=issueTagPasskeyChallenge({tagId,purpose:'register',ownerId:null,credentialId:null,scope},now);
 const stored=await verifyTagRegistration(reg,auth.register(await tagRegistrationOptions(reg,now)),now);
 await db.collection('kyrub_official_tags').doc(tagId).set({ownerId,ownerAuthMode:'passkey',enabled:true,blocked:false});
 await db.collection('kyrub_tag_passkey_credentials').doc(tagId).set({ownerId,credential:stored});
 await db.collection('kyrub_tag_passkey_credential_index').doc(hash(stored.id)).set({ownerId,tagId});
 const central=createCidOwnerCentralEmulator(tagId),ceremony=await central.begin(origin,now+1);
 const session=await central.finish(origin,ceremony.challengeId,auth.assert(ceremony.options),now+2);
 assert.equal((await central.readConfig(session,now+3))?.revision,1);
 const newPerson={id:'new-contact',name:'Contato novo',channels:[{channel:'email',address:'new@example.invalid'}]};
 const draft={expectedRevision:1,enabled:true,owner:config.owner,contacts:[newPerson]};
 await assert.rejects(central.beginConfigChange({...session,secret:randomBytes(32).toString('base64url')},origin,draft,now+3));
 await assert.rejects(central.beginConfigChange(session,origin,{...draft,contacts:[{...newPerson,channels:[{...newPerson.channels[0],verified:true}]}]},now+3));
 const change=await central.beginConfigChange(session,origin,draft,now+3);
 const answer=auth.assert(change.options);
 assert.equal((await central.readConfig(session,now+4))?.revision,1);
 assert.equal((await central.finishConfigChange(session,origin,change.challengeId,answer,now+4)).revision,2);
 await assert.rejects(central.finishConfigChange(session,origin,change.challengeId,answer,now+5));
 await assert.rejects(central.beginConfigChange(session,origin,draft,now+5));
 assert.equal((await central.read(session,now+5)).sos.available,false);
 assert.ok((await grantRef.get()).get('grants').find((g:ChannelGrant)=>g.participantId==='contact-test').revokedAt);
 await assert.rejects(central.prepareChannelConsentForDelivery(session,'contact-test','email',now+6));
 const proof=await central.prepareChannelConsentForDelivery(session,'new-contact','email',now+6);
 assert.equal(proof.deliveryEnvelope.route.address,'new@example.invalid');
 assert.ok(!JSON.stringify(proof.publicResult).includes(proof.deliveryEnvelope.secret));
 await assert.rejects(central.confirmChannelConsent(proof.publicResult.challengeId,proof.deliveryEnvelope.secret,false,now+7));
 await assert.rejects(central.confirmChannelConsent(proof.publicResult.challengeId,randomBytes(32).toString('base64url'),true,now+7));
 const results=await Promise.allSettled([central.confirmChannelConsent(proof.publicResult.challengeId,proof.deliveryEnvelope.secret,true,now+8),central.confirmChannelConsent(proof.publicResult.challengeId,proof.deliveryEnvelope.secret,true,now+8)]);
 const success=results.filter(r=>r.status==='fulfilled');assert.equal(success.length,1);
 const result=success[0];assert.ok(result.status==='fulfilled');
 const revocation=result.value.revocation;
 assert.equal((await central.read(session,now+9)).sos.available,true);
 const emitter=await createCidSosEmulatorStore(tagId).submitEmitterAlert({id,confirmed:true,reason:'Animal encontrado',sms:false},randomBytes(32).toString('base64url'),now+10);
 await assert.rejects(central.readConfig(emitter.session,now+11));
 const chat=createCidChatEmulatorStore(tagId,id);
 const invitation=await chat.prepareContactInvitationForDelivery('new-contact','email',now+11);
 const challenge=await chat.prepareContactConfirmationForDelivery(invitation.invitation,now+12);
 const contact=await chat.confirmContact(invitation.invitation,challenge.publicResult.challengeId,challenge.deliveryEnvelope.secret,now+13);
 await assert.rejects(central.revokeChannelConsent(revocation.id,'wrong',now+14));
 assert.equal((await central.revokeChannelConsent(revocation.id,revocation.secret,now+14)).revoked,true);
 assert.equal((await central.read(session,now+15)).sos.available,false);
 await assert.rejects(chat.read(contact,now+15));
 const renewed=await central.prepareChannelConsentForDelivery(session,'new-contact','email',now+16);
 await central.confirmChannelConsent(renewed.publicResult.challengeId,renewed.deliveryEnvelope.secret,true,now+17);
 assert.equal((await central.read(session,now+18)).sos.available,true);
 await assert.rejects(chat.read(contact,now+18));
 await assert.rejects(central.revokeChannelConsent(revocation.id,revocation.secret,now+18));
 const persisted=(await grantRef.get()).get('grants');
 assert.ok(!JSON.stringify(persisted).includes(proof.deliveryEnvelope.secret));
 assert.ok(!JSON.stringify(persisted).includes(revocation.secret));
});
