import assert from 'node:assert/strict';
import {test} from 'node:test';
import {initializeApp,deleteApp} from 'firebase-admin/app';
import {getAuth} from 'firebase-admin/auth';
import {getFirestore} from 'firebase-admin/firestore';
import {searchStoreStaffDirectory,createStoreStaffInvitation} from '../server/identity/storeStaffDirectoryService';
import {lookupAdminDirectoryIdentity,countAdminDirectoryUsers} from '../server/identity/adminDirectoryIdentityService';
import {staffDirectoryPilotEnabled} from '../server/identity/storeStaffDirectoryEmulatorRouter';
import {adminDirectoryPilotEnabled} from '../server/identity/adminDirectoryEmulatorRouter';

test('isolated professional and administrative directory: scope, minimum projection and audit',async()=>{
 assert.equal(process.env.FIRESTORE_EMULATOR_HOST,'127.0.0.1:8088');
 assert.equal(process.env.FIREBASE_AUTH_EMULATOR_HOST,'127.0.0.1:9099');
 assert.equal(process.env.GCLOUD_PROJECT,'demo-kyrub-welcome');
 const app=initializeApp({projectId:'demo-kyrub-welcome'},'professional-directory-test');
 const db=getFirestore(app),auth=getAuth(app);
 try{
  assert.ok(staffDirectoryPilotEnabled(db));
  assert.ok(adminDirectoryPilotEnabled(db));
  assert.equal(staffDirectoryPilotEnabled(db,{...process.env,NODE_ENV:'development'}),false);
  assert.equal(adminDirectoryPilotEnabled(db,{...process.env,VERCEL:'1'}),false);
  const owner=await auth.createUser({uid:'owner',email:'owner@example.invalid',emailVerified:true});
  const manager=await auth.createUser({uid:'manager',email:'manager@example.invalid',emailVerified:true});
  const target=await auth.createUser({uid:'target',email:'target@example.invalid',emailVerified:true});
  const admin=await auth.createUser({uid:'admin',email:'admin@example.invalid',emailVerified:true});
  await db.doc('users/'+target.uid).set({uid:target.uid,name:'Reservado',email:'fake@example.invalid',isProfileVisible:false,cpf:'synthetic',phone:'synthetic'});
  const store=db.doc('stores/store');
  await store.set({id:'store',ownerId:owner.uid,name:'Loja de teste'});
  await store.collection('members').doc(manager.uid).set({storeId:'store',userId:manager.uid,role:'manager',status:'active'});
  const search=(actor:string,term:string,role='seller')=>searchStoreStaffDirectory(db,auth,actor,'store',term,role);
  await assert.rejects(search('outsider','target@example.invalid'),/STAFF_DIRECTORY_FORBIDDEN/);
  await assert.rejects(search(manager.uid,'target@example.invalid','manager'),/STAFF_DIRECTORY_FORBIDDEN/);
  assert.deepEqual(await search(owner.uid,'Reservado'),[]);
  assert.deepEqual(await search(owner.uid,'fake@example.invalid'),[]);
  assert.deepEqual(await search(owner.uid,'target@example.invalid'),[{uid:target.uid,name:'Conta Kyrub',photoUrl:''}]);
  assert.deepEqual(await search(manager.uid,'target@example.invalid'),[{uid:target.uid,name:'Conta Kyrub',photoUrl:''}]);
  const control=db.doc('erp_age_release_private/current');
  await control.set({schemaVersion:1,mode:'verified_adult_only'});
  const invite=()=>createStoreStaffInvitation(db,auth,owner.uid,'store',target.uid,'target@example.invalid','seller');
  await assert.rejects(invite(),/STAFF_DIRECTORY_AGE_REQUIRED/);
  await db.doc('age_eligibility_private/'+owner.uid).set({uid:owner.uid,status:'verified_adult'});
  await db.doc('age_eligibility_private/'+target.uid).set({uid:target.uid,status:'verified_adult'});
  const results=await Promise.allSettled([invite(),invite()]);
  assert.equal(results.filter(x=>x.status==='fulfilled').length,1);
  assert.equal(results.filter(x=>x.status==='rejected').length,1);
  const membership=(await store.collection('members').doc(target.uid).get()).data()!;
  assert.equal(membership.status,'invited');
  assert.equal(membership.email,'');
  assert.equal(membership.displayName,'Conta Kyrub');
  assert.equal(membership.photoUrl,'');
  assert.equal(membership.cpf,undefined);
  await assert.rejects(lookupAdminDirectoryIdentity(db,auth,'outsider',target.uid),/ADMIN_DIRECTORY_FORBIDDEN/);
  const grant=db.doc('kyrub_admin/control_plane/admins/'+admin.uid);
  await grant.set({uid:admin.uid,role:'support',status:'active'});
  const record=await lookupAdminDirectoryIdentity(db,auth,admin.uid,'target@example.invalid');
  assert.ok(record);
  assert.equal(record.email,'target@example.invalid');
  assert.equal(record.uid,target.uid);
  assert.deepEqual(Object.keys(record).sort(),['createdAt','email','isProfileVisible','name','photoUrl','uid','updatedAt']);
  assert.equal(await countAdminDirectoryUsers(db,admin.uid),1);
  const audit=await db.collection('kyrub_admin/control_plane/audit_logs').get();
  assert.equal(audit.size,1);
  assert.equal(audit.docs[0].get('targetId'),target.uid);
  assert.doesNotMatch(JSON.stringify(audit.docs[0].data()),/target@example/);
  await grant.update({status:'suspended'});
  await assert.rejects(countAdminDirectoryUsers(db,admin.uid),/ADMIN_DIRECTORY_FORBIDDEN/);
 }finally{await db.terminate();await deleteApp(app);}
});
