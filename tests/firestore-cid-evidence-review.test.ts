import assert from 'node:assert/strict';
import {test,after} from 'node:test';
import {randomBytes,createHash} from 'node:crypto';
import {initializeApp,getApps,deleteApp} from 'firebase-admin/app';
import {getFirestore} from 'firebase-admin/firestore';
import {assertCidSosEmulator,CID_EMULATOR_PROJECT,createCidSosEmulatorStore} from '../server/identity/cidSosEmulatorStore';
import {createCidEvidenceReviewEmulator} from '../server/identity/cidEvidenceReviewEmulator';
import {createCidChatEmulatorStore,CID_CHAT_EMULATOR_ORIGIN as origin} from '../server/identity/cidChatEmulatorStore';
import {createCidSosNotificationEmulator} from '../server/identity/cidSosNotificationEmulator';
import {prepareCidSosConfig,type ChannelGrant} from '../server/identity/cidSosPrivateConfig';
import {isolatedTagPasskeyScope,issueTagPasskeyChallenge} from '../server/identity/kyrubTagPasskeyPolicy';
import {tagRegistrationOptions,verifyTagRegistration} from '../server/identity/kyrubTagPasskeyVerifier';
import {makeSoftwareTagAuthenticator} from './fixtures/kyrub-tag-software-authenticator';
import {normalizeCidSosResolution,cidSosResolutionNotice} from '../shared/cidSosResolution';

assertCidSosEmulator();
const app=initializeApp({projectId:CID_EMULATOR_PROJECT},'cid-resolution-fixtures');
const db=getFirestore(app),now=Date.UTC(2026,10,26,12);
const tagId='a'.repeat(32),ownerId='owner-test',id='b'.repeat(32);
const tag={tagId,ownerId,displayName:'CID fictício',active:true};
const root=db.collection('cid_sos_emulator_tags').doc(tagId);
const person=(id:string)=>({id,name:id,channels:[{channel:'email',address:id+'@example.invalid'}]});
const config=prepareCidSosConfig(tag,ownerId,null,{expectedRevision:0,enabled:true,owner:person(ownerId),contacts:[person('contact-a'),person('contact-b'),person('contact-c')]});
const grants:ChannelGrant[]=[config.owner,...config.contacts].flatMap(p=>p.channels.map(c=>({...c,tagId,ownerId,participantId:p.id,verifiedAt:now-1000,consent:true})));
const hash=(x:string)=>createHash('sha256').update(x).digest('hex');
after(async()=>{for(const a of getApps().filter(a=>['cid-resolution-fixtures','cid-sos-local-emulator','cid-chat-local-emulator','cid-notification-local-emulator','cid-evidence-review-local-emulator'].includes(a.name)))await deleteApp(a);});
test('review queue is restricted, audited and never authorizes retention or disclosure',async()=>{
 await root.set({tag,revision:0});
 await root.collection('private').doc('config').set({config});await root.collection('private').doc('grants').set({grants});
 const scope=isolatedTagPasskeyScope(origin,origin),auth=makeSoftwareTagAuthenticator(origin,scope.rpId);
 const registration=issueTagPasskeyChallenge({tagId,purpose:'register',ownerId:null,credentialId:null,scope},now);
 const stored=await verifyTagRegistration(registration,auth.register(await tagRegistrationOptions(registration,now)),now);
 await db.collection('kyrub_official_tags').doc(tagId).set({ownerId,ownerAuthMode:'passkey',enabled:true,blocked:false});
 await db.collection('kyrub_tag_passkey_credentials').doc(tagId).set({ownerId,credential:stored});
 await db.collection('kyrub_tag_passkey_credential_index').doc(hash(stored.id)).set({ownerId,tagId});
 const emitter=await createCidSosEmulatorStore(tagId).submitEmitterAlert({id,confirmed:true,reason:'Animal encontrado',sms:false},randomBytes(32).toString('base64url'),now+1);
 const chat=createCidChatEmulatorStore(tagId,id);
 const ceremony=await chat.beginOwnerPasskey(origin,now+2),owner=await chat.finishOwnerPasskey(origin,ceremony.challengeId,auth.assert(ceremony.options),now+3);
 const complaint=await chat.denounceOccurrence(emitter.session,{category:'privacy',reason:'Relato fictício',confirmed:true},now+4);
 const preserve=await chat.preserveEvidence(owner,'Preservar conversa',now+5);
 const review=createCidEvidenceReviewEmulator();
 const permissions=['review:read','review:decide'],actorId='review-fixture';
 const operators=db.collection('cid_sos_emulator_review_operators'),sessions=db.collection('cid_sos_emulator_review_sessions');
 await operators.doc(actorId).set({active:true,role:'evidence-officer',permissions});
 const issue=async(perms:string[],authenticatedAt:number)=>{
  const credential={id:randomBytes(32).toString('base64url'),secret:randomBytes(32).toString('base64url')};
  await sessions.doc(credential.id).set({id:credential.id,actorId,role:'evidence-officer',permissions:perms,simulation:true,digest:hash(credential.secret),authenticatedAt,expiresAt:authenticatedAt+1800000});
  return credential;
 };
 const admin=await issue(permissions,now+6),reader=await issue(['review:read'],now+6);
 await assert.rejects(review.list(owner,now+7));
 await assert.rejects(review.list({...admin,secret:randomBytes(32).toString('base64url')},now+7));
 const listed=await review.list(reader,now+7);
 assert.equal(listed.items.length,2);assert.ok(!JSON.stringify(listed).includes('Relato fictício'));
 const detail=await review.detail(admin,complaint.id,now+8);
 assert.equal(detail.reason,'Relato fictício');assert.equal(detail.reporterRole,'emitter');
 assert.ok(!JSON.stringify(detail).includes('example.invalid'));assert.ok(!JSON.stringify(detail).includes(emitter.session.secret));
 const input={id:complaint.id,expectedRevision:0,disposition:'escalated',reason:'Revisão especializada necessária'};
 await assert.rejects(review.decide(reader,input,now+9));
 await assert.rejects(review.decide(admin,{...input,disposition:'approved'},now+9));
 await assert.rejects(review.decide(admin,{...input,allowedFields:['sourceIp']},now+9));
 const concurrent=await Promise.allSettled([review.decide(admin,input,now+10),review.decide(admin,input,now+10)]);
 assert.equal(concurrent.filter(x=>x.status==='fulfilled').length,1);
 assert.equal((await review.detail(admin,complaint.id,now+11)).item.status,'escalated');
 const stale=now+306007;
 await assert.rejects(review.decide(admin,{id:preserve.id,expectedRevision:0,disposition:'dismissed',reason:'Análise encerrada'},stale));
 const fresh=await issue(permissions,stale);
 await review.decide(fresh,{id:preserve.id,expectedRevision:0,disposition:'dismissed',reason:'Análise encerrada'},stale+1);
 const audit=(await db.collection('cid_sos_emulator_review_audit').get()).docs.map(d=>d.data());
 assert.equal(audit.filter(x=>x.action==='triage-decision').length,2);
 assert.ok(audit.every(x=>x.actorId===actorId&&x.simulation===true));
 assert.ok(!JSON.stringify(audit).includes(admin.secret));
 const state=root.collection('occurrences').doc(id).collection('chat').doc('state');
 assert.equal((await state.collection('private').doc('preservation-request').get()).get('request.status'),'pending-review');
 assert.equal((await root.collection('occurrences').doc(id).get()).get('status'),'open');
 await operators.doc(actorId).update({active:false});
 await assert.rejects(review.list(fresh,stale+2));
});
