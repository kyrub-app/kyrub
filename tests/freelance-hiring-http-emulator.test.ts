import assert from 'node:assert/strict';
import {once} from 'node:events';
import {test} from 'node:test';
import express from 'express';
import {initializeApp,deleteApp} from 'firebase/app';
import {getAuth,connectAuthEmulator,signInWithEmailAndPassword} from 'firebase/auth';
import {getFirestore,connectFirestoreEmulator,doc,setDoc,getDocFromServer,updateDoc,deleteDoc,collection,getDocsFromServer,query,limit,serverTimestamp,terminate} from 'firebase/firestore';

test('isolated authenticated hiring journey preserves private messages and atomic bell events',async()=>{
 assert.equal(process.env.FIREBASE_AUTH_EMULATOR_HOST,'127.0.0.1:9099');
 assert.equal(process.env.FIRESTORE_EMULATOR_HOST,'127.0.0.1:8088');
 assert.equal(process.env.FIREBASE_PROJECT_ID,'kyrub-security-test');
 assert.equal(process.env.KYRUB_FREELANCE_NOTIFICATION_PREVIEW,'true');
 assert.notEqual(process.env.NODE_ENV,'production');
 assert.ok(!process.env.VERCEL&&!process.env.FIREBASE_SERVICE_ACCOUNT_JSON&&!process.env.GOOGLE_APPLICATION_CREDENTIALS);
 const {adminAuth,adminDb}=await import('../server/firebaseAdmin.js');
 const {createUserNotificationRouter}=await import('../server/notifications/userNotificationRouter.js');
 const {createUserCommunicationPreferenceRouter}=await import('../server/notifications/userCommunicationPreferenceRouter.js');
 const api=express();
 api.use(express.json());
 api.use('/api/notifications',createUserNotificationRouter());
 api.use('/api/communication-preferences',createUserCommunicationPreferenceRouter());
 const server=api.listen(0,'127.0.0.1');
 await once(server,'listening');
 const address=server.address();
 assert.ok(address&&typeof address==='object');
 const base='http://127.0.0.1:'+address.port;
 const clients: {app:ReturnType<typeof initializeApp>;db:ReturnType<typeof getFirestore>}[]=[];
 try{
  await adminDb.doc('renda_age_release_private/current').set({schemaVersion:1,mode:'verified_adult_only',messageAuthority:'server',applicationAuthority:'server',vacancyPolicy:'lock_on_application'});
  const account=async(name:string,profile:string,role?:string)=>{
   const uid='http_freela_'+name,email=uid+'@example.invalid',password='SyntheticOnly-Password1';
   await adminAuth.createUser({uid,email,password,emailVerified:true});
   if(role)await adminAuth.setCustomUserClaims(uid,{role});
   await adminDb.doc('age_eligibility_private/'+uid).set({uid,status:'verified_adult'});
   await adminDb.doc('identity_verifications/'+uid).set({uid,status:'approved',approvedProfiles:[profile]});
   const app=initializeApp({projectId:'kyrub-security-test',apiKey:'fake-emulator-key'},uid);
   const auth=getAuth(app);
   connectAuthEmulator(auth,'http://127.0.0.1:9099',{disableWarnings:true});
   const db=getFirestore(app);connectFirestoreEmulator(db,'127.0.0.1',8088);
   clients.push({app,db});
   const login=await signInWithEmailAndPassword(auth,email,password);
   return {uid,db,token:await login.user.getIdToken()};
  };
  const owner=await account('owner','requester','owner');
  const worker=await account('worker','freelancer');
  const outsider=await account('outsider','freelancer');
  const vacancy=doc(collection(owner.db,'vagas'));
  await setDoc(vacancy,{ownerId:owner.uid,title:'Vaga fictícia',description:'Trabalho sintético',payment:90,termsLocked:false,hasAccepted:false,employer:'Contratante de teste',status:'open',createdAt:serverTimestamp(),updatedAt:serverTimestamp()});
  await updateDoc(vacancy,{payment:100,updatedAt:serverTimestamp()});
  assert.equal((await getDocFromServer(vacancy)).get('payment'),100);
  const applicationId=vacancy.id+'__'+worker.uid;
  const receipt=(db:typeof owner.db)=>doc(db,'candidaturas',applicationId);
  const call=(token:string,path:string,body?:unknown,method=body===undefined?'GET':'POST')=>fetch(base+path,{method,headers:{authorization:'Bearer '+token,'content-type':'application/json'},...(body===undefined?{}:{body:JSON.stringify(body)})});
  const terms={schemaVersion:1,title:'Vaga fictícia',description:'Trabalho sintético',paymentCents:10000,currency:'BRL'};
  const action=(token:string,action:string,operationId:string,expectedTerms=terms)=>call(token,'/api/notifications/freelance-applications/action',{applicationId,action,operationId,expectedTerms});
  const send=(token:string,messageId:string,text:string)=>call(token,'/api/notifications/freelance-messages/send',{applicationId,messageId,text});
  const inbox=async(token:string)=>{const res=await call(token,'/api/notifications');assert.equal(res.status,200);return res.json();};
  const ok=async(response:Response)=>{const payload=await response.json();assert.equal(response.status,200,JSON.stringify(payload));return payload;};
  assert.equal((await call('forged','/api/notifications')).status,401);
  await assert.rejects(setDoc(receipt(worker.db),{vagaId:vacancy.id,ownerId:owner.uid,userId:worker.uid,status:'pending',createdAt:serverTimestamp(),updatedAt:serverTimestamp()}));
  assert.equal((await action(outsider.token,'apply','forged')).status,403);
  assert.equal((await action(worker.token,'apply','stale',{...terms,paymentCents:9000})).status,409);
  assert.equal((await ok(await action(worker.token,'apply','apply-1'))).created,true);
  assert.equal((await ok(await action(worker.token,'apply','apply-1'))).created,false);
  assert.equal((await inbox(owner.token)).unreadCount,1);
  await assert.rejects(getDocFromServer(receipt(outsider.db)));
  assert.equal((await action(worker.token,'accept','forged-accept')).status,403);
  await assert.rejects(updateDoc(receipt(owner.db),{status:'accepted',updatedAt:serverTimestamp()}));
  const confidential='Condições privadas do turno fictício';
  assert.equal((await ok(await send(worker.token,'message-one',confidential))).created,true);
  assert.equal((await ok(await send(worker.token,'message-one',confidential))).created,false);
  assert.equal((await send(worker.token,'message-one','alterada')).status,409);
  assert.equal((await send(outsider.token,'intrusion','intrusão')).status,403);
  const message=(db:typeof owner.db)=>doc(db,'candidaturas',applicationId,'messages','message-one');
  assert.equal((await getDocFromServer(message(owner.db))).get('text'),confidential);
  await assert.rejects(getDocFromServer(message(outsider.db)));
  await assert.rejects(updateDoc(message(worker.db),{text:'alterada'}));
  await assert.rejects(deleteDoc(message(owner.db)));
  await assert.rejects(setDoc(doc(owner.db,'candidaturas',applicationId,'messages','bypass'),{senderId:owner.uid,receiverId:worker.uid,text:'bypass',createdAt:serverTimestamp()}));
  const notices=await inbox(owner.token);
  assert.equal(notices.unreadCount,2);
  assert.ok(!JSON.stringify(notices).includes(confidential));
  const noticeId=notices.notifications.find((n:{eventType:string})=>n.eventType==='message_received').id;
  assert.equal((await call(outsider.token,'/api/notifications/read',{notificationId:noticeId})).status,404);
  assert.equal((await call(owner.token,'/api/notifications/read',{notificationId:noticeId})).status,204);
  assert.equal((await inbox(owner.token)).unreadCount,1);
  assert.equal((await inbox(outsider.token)).unreadCount,0);
  const preferences=await ok(await call(owner.token,'/api/communication-preferences'));
  assert.equal(preferences.browser.categories.freelance,false);
  assert.equal((await getDocFromServer(vacancy)).get('termsLocked'),true);
  await assert.rejects(updateDoc(vacancy,{payment:200,description:'Condições futuras',updatedAt:serverTimestamp()}));
  await assert.rejects(updateDoc(vacancy,{termsLocked:false,updatedAt:serverTimestamp()}));
  await assert.rejects(deleteDoc(vacancy));
  assert.equal((await action(owner.token,'accept','wrong-terms',{...terms,paymentCents:20000})).status,409);
  await ok(await action(owner.token,'accept','accept-1'));
  assert.equal((await getDocFromServer(vacancy)).get('hasAccepted'),true);
  assert.deepEqual((await getDocFromServer(receipt(worker.db))).get('terms'),terms);
  await assert.rejects(updateDoc(receipt(owner.db),{'terms.paymentCents':1}));
  await ok(await action(worker.token,'request_completion','completion-1'));
  await ok(await action(owner.token,'request_review','review-1'));
  await ok(await action(worker.token,'request_completion','completion-2'));
  await ok(await action(owner.token,'complete','complete-1'));
  const final=await getDocFromServer(receipt(worker.db));
  assert.equal(final.get('status'),'completed');
  assert.equal(final.get('paymentStatus'),undefined);
  assert.deepEqual(final.get('terms'),terms);
  assert.ok(final.get('acceptedAt'));
  assert.equal((await getDocsFromServer(query(collection(worker.db,'candidaturas',applicationId,'messages'),limit(50)))).size,1);
  assert.equal((await send(worker.token,'late','tardia')).status,403);
  assert.equal((await inbox(owner.token)).notifications.length,4);
  assert.equal((await inbox(worker.token)).notifications.length,3);
  await assert.rejects(deleteDoc(receipt(worker.db)));
  await adminAuth.updateUser(worker.uid,{disabled:true});
  assert.equal((await call(worker.token,'/api/notifications')).status,401);
  assert.equal((await action(worker.token,'apply','apply-1')).status,401);
 }finally{
  for(const client of clients){await terminate(client.db);await deleteApp(client.app);}
  server.closeAllConnections();await new Promise<void>(resolve=>server.close(()=>resolve()));
  await adminDb.terminate();
 }
});
