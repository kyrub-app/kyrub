import assert from 'node:assert/strict';
import {test,after} from 'node:test';
import {randomBytes} from 'node:crypto';
import {mkdtempSync,readFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {execFileSync} from 'node:child_process';
import {createServer,request} from 'node:https';
import {initializeApp,getApps,deleteApp} from 'firebase-admin/app';
import {getFirestore} from 'firebase-admin/firestore';
import {assertCidSosEmulator,CID_EMULATOR_PROJECT} from '../server/identity/cidSosEmulatorStore';
import {createCidSosHttpEmulatorHandler} from '../server/identity/cidSosHttpEmulator';
import {CID_CHAT_EMULATOR_ORIGIN as origin,createCidChatEmulatorStore} from '../server/identity/cidChatEmulatorStore';
import {prepareCidSosConfig,type ChannelGrant} from '../server/identity/cidSosPrivateConfig';
assertCidSosEmulator();
const app=initializeApp({projectId:CID_EMULATOR_PROJECT},'cid-http-fixtures');
const db=getFirestore(app),now=Date.now();
const tagId='a'.repeat(32),id='b'.repeat(32),ownerId='owner-test';
const tag={tagId,ownerId,displayName:'CID fictício',active:true};
const root=db.collection('cid_sos_emulator_tags').doc(tagId);
const person=(id:string)=>({id,name:id,channels:[{channel:'email',address:id+'@example.invalid'}]});
const config=prepareCidSosConfig(tag,ownerId,null,{expectedRevision:0,enabled:true,owner:person(ownerId),contacts:[person('contact-test')]});
const grants:ChannelGrant[]=[config.owner,...config.contacts].flatMap(p=>p.channels.map(c=>({...c,tagId,ownerId,participantId:p.id,verifiedAt:now-1000,consent:true})));
const token=()=>randomBytes(32).toString('base64url');
after(async()=>{for(const a of getApps().filter(a=>['cid-http-fixtures','cid-sos-local-emulator','cid-chat-local-emulator'].includes(a.name)))await deleteApp(a);});
test('standalone local TLS handler protects chat credentials and contact confirmation',async()=>{
 await root.set({tag,revision:0});
 await root.collection('private').doc('config').set({config});
 await root.collection('private').doc('grants').set({grants});
 const directory=mkdtempSync(join(tmpdir(),'cid-tls-'));
 const key=join(directory,'key.pem'),cert=join(directory,'cert.pem');
 execFileSync('openssl',['req','-x509','-newkey','rsa:2048','-nodes','-keyout',key,'-out',cert,'-days','1','-subj','/CN=kyrub-cid-emulator.vercel.app'],{stdio:'ignore'});
 let confirmation='';
 const server=createServer({key:readFileSync(key),cert:readFileSync(cert)},createCidSosHttpEmulatorHandler(async envelope=>{assert.equal(envelope.route.address,'contact-test@example.invalid');confirmation=envelope.secret;}));
 try{
  await new Promise<void>(resolve=>server.listen(0,'127.0.0.1',resolve));
  const address=server.address();assert.ok(address&&typeof address==='object');
  const base='/cid-homologation/api/'+tagId+'/'+id+'/';
  const call=(action:string,data:unknown,cookie='',override:Record<string,string>={})=>new Promise<{status:number;body:any;cookies:string[];cache:string|undefined}>((resolve,reject)=>{
   const req=request({hostname:'127.0.0.1',port:address.port,path:base+action,method:'POST',rejectUnauthorized:false,headers:{Host:new URL(origin).host,Origin:origin,'X-Cid-Homologation':'1','Content-Type':'application/json',Cookie:cookie,...override}},res=>{
    const chunks:Buffer[]=[];res.on('data',c=>chunks.push(Buffer.from(c)));res.on('end',()=>{try{resolve({status:res.statusCode??0,body:JSON.parse(Buffer.concat(chunks).toString()),cookies:res.headers['set-cookie']??[],cache:res.headers['cache-control']});}catch(e){reject(e);}});
   });req.on('error',reject);req.end(JSON.stringify(data));
  });
  const alert={id,confirmed:true,reason:'Animal encontrado',sms:false},seed=token();
  assert.equal((await call('emit',{request:alert,seed},'',{Origin:'https://foreign.example'})).status,403);
  assert.equal((await call('emit',{request:alert,seed},'',{'X-Cid-Homologation':'0'})).status,403);
  assert.equal((await call('emit',{request:alert,seed,now:1})).status,403);
  assert.equal((await root.collection('occurrences').get()).size,0);
  const emitted=await call('emit',{request:alert,seed});
  assert.equal(emitted.status,200);assert.deepEqual(emitted.body,{accepted:true,simulated:true});
  assert.equal(emitted.cache,'no-store');assert.equal(emitted.cookies.length,1);
  const header=emitted.cookies[0];
  for(const attribute of ['HttpOnly','Secure','SameSite=Strict','Path='+base])assert.ok(header.includes(attribute));
  const session=header.split(';')[0];
  assert.equal((await call('read',{})).status,403);
  assert.equal((await call('read?secret=bad',{},session)).status,404);
  assert.equal((await call('read',{},session+'; '+session)).status,403);
  assert.equal((await call('read',{},session,{'Sec-Fetch-Site':'cross-site'})).status,403);
  assert.equal((await call('read',{},session)).body.role,'emitter');
  assert.equal((await call('send',{id:'msg-a',body:'Encontrei o animal.'},session)).status,200);
  assert.equal((await call('close',{},session)).status,403);
  assert.equal((await call('send',{id:'msg-b',body:'texto',authorId:ownerId},session)).status,403);
  const chat=createCidChatEmulatorStore(tagId,id);
  const issued=await chat.prepareContactInvitationForDelivery('contact-test','email',Date.now());
  const challenge=await call('contact-request',{invitation:issued.invitation});
  assert.equal(challenge.status,200);assert.ok(confirmation);
  assert.ok(!JSON.stringify(challenge.body).includes(confirmation));
  assert.ok(!JSON.stringify(challenge.body).includes('example.invalid'));
  const contact=await call('contact-confirm',{invitation:issued.invitation,challengeId:challenge.body.challengeId,confirmation});
  assert.equal(contact.status,200);
  const contactCookie=contact.cookies[0].split(';')[0];
  const view=await call('read',{},contactCookie);
  assert.equal(view.body.role,'contact');assert.match(JSON.stringify(view.body),/Encontrei o animal/);
  assert.ok(!JSON.stringify(view.body).includes('example.invalid'));
  const revoked=await call('revoke',{},contactCookie);assert.equal(revoked.status,200);assert.match(revoked.cookies[0],/Max-Age=0/);
  assert.equal((await call('read',{},contactCookie)).status,403);
  assert.equal((await call('read',{},session)).status,200);
  assert.equal((await root.collection('outbox').get()).size,2);
 }finally{await new Promise<void>(resolve=>server.close(()=>resolve()));rmSync(directory,{recursive:true,force:true});}
});
