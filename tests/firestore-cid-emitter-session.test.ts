import assert from 'node:assert/strict';
import {test,after} from 'node:test';
import {randomBytes} from 'node:crypto';
import {initializeApp,getApps,deleteApp} from 'firebase-admin/app';
import {getFirestore} from 'firebase-admin/firestore';
import {assertCidSosEmulator,CID_EMULATOR_PROJECT,createCidSosEmulatorStore} from '../server/identity/cidSosEmulatorStore';
import {createCidChatEmulatorStore} from '../server/identity/cidChatEmulatorStore';
import {prepareCidSosConfig,type ChannelGrant} from '../server/identity/cidSosPrivateConfig';
assertCidSosEmulator();
const app=initializeApp({projectId:CID_EMULATOR_PROJECT},'cid-emitter-fixtures');
const db=getFirestore(app),now=Date.UTC(2026,10,26,12);
const tag={tagId:'a'.repeat(32),ownerId:'owner-test',displayName:'CID fictício',active:true};
const root=db.collection('cid_sos_emulator_tags').doc(tag.tagId);
const person=(id:string)=>({id,name:id,channels:[{channel:'email',address:id+'@example.invalid'}]});
const config=prepareCidSosConfig(tag,tag.ownerId,null,{expectedRevision:0,enabled:true,owner:person(tag.ownerId),contacts:[person('contact-test')]});
const grants:ChannelGrant[]=[config.owner,...config.contacts].flatMap(p=>p.channels.map(c=>({...c,tagId:tag.tagId,ownerId:tag.ownerId,participantId:p.id,verifiedAt:now-1000,consent:true})));
const request={id:'b'.repeat(32),confirmed:true,reason:'Animal encontrado',sms:false};
const seed=()=>randomBytes(32).toString('base64url');
after(async()=>{for(const a of getApps().filter(a=>['cid-emitter-fixtures','cid-sos-local-emulator','cid-chat-local-emulator'].includes(a.name)))await deleteApp(a);});
test('emitter obtains scoped possession session atomically with SOS, no fixture identity',async()=>{
 await root.set({tag,revision:0});
 await root.collection('private').doc('config').set({config});
 await root.collection('private').doc('grants').set({grants});
 const sos=createCidSosEmulatorStore(tag.tagId),key=seed();
 await assert.rejects(sos.submitEmitterAlert({...request,confirmed:false},key,now));
 await assert.rejects(sos.submitEmitterAlert(request,'invalid',now));
 assert.equal((await root.collection('occurrences').get()).size,0);
 const race=await Promise.all([sos.submitEmitterAlert(request,key,now),sos.submitEmitterAlert(request,key,now)]);
 assert.deepEqual(race[0],race[1]);
 const result=race[0],chat=createCidChatEmulatorStore(tag.tagId,request.id);
 const ref=root.collection('occurrences').doc(request.id),state=ref.collection('chat').doc('state');
 assert.equal((await root.collection('occurrences').get()).size,1);
 assert.equal((await root.collection('outbox').get()).size,2);
 assert.equal((await state.collection('sessions').get()).size,1);
 assert.equal((await state.collection('messages').get()).size,1);
 assert.equal((await state.collection('fixtureProofs').get()).size,0);
 assert.equal((await chat.read(result.session,now+1)).role,'emitter');
 assert.equal((await chat.read(result.session,now+1)).reason,request.reason);
 await assert.rejects(sos.submitEmitterAlert(request,seed(),now+1));
 await assert.rejects(sos.submitEmitterAlert({...request,reason:'Outro motivo'},key,now+1));
 await assert.rejects(sos.submitEmitterAlert({...request,id:'c'.repeat(32)},key,now+1));
 assert.equal((await root.collection('occurrences').get()).size,1);
 await chat.send(result.session,{id:'msg-a',body:'Encontrei o animal.'},now+2);
 await assert.rejects(chat.close(result.session,now+3));
 const privateRecord=JSON.stringify((await ref.collection('private').doc('emitter').get()).data());
 assert.ok(!privateRecord.includes(key)&&!privateRecord.includes(result.session.secret));
 await chat.revokeOwnSession(result.session,now+4);
 await assert.rejects(sos.submitEmitterAlert(request,key,now+5));
 assert.equal((await root.collection('outbox').get()).size,2);
});
