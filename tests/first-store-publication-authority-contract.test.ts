import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const canonicalRules = readFileSync(new URL('../firestore.store-security.fragment.rules', import.meta.url), 'utf8');
const modal = readFileSync(new URL('../src/components/modals/StoreConfigModal.tsx', import.meta.url), 'utf8');
const source = readFileSync(new URL('../server/gamification/firstStorePublicationAuthority.ts', import.meta.url), 'utf8');

test('publication authority is server-only and requires canonical owner and first-store marker', () => {
  assert.match(source, /authenticatedUserId/);
  assert.match(source, /store\.get\('ownerId'\) !== uid/);
  assert.match(source, /firstStoreCreationVerified/);
  assert.match(source, /listing\.get\('ownerId'\) !== uid/);
});

test('publication, verified event and XP share one Firestore transaction', () => {
  assert.match(source, /db\.runTransaction/);
  assert.match(source, /awardVerifiedFirstStorePublicationInTransaction\(tx/);
  assert.match(source, /tx\.update\(storeRef/);
  assert.match(source, /tx\.update\(listingRef/);
  assert.match(source, /tx\.create\(eventRef/);
});

test('publication marker cannot be replaced by a second request', () => {
  assert.match(source, /existingFirstAt \|\| event\.exists/);
  assert.match(source, /FIRST_STORE_PUBLICATION_MARKER_CONFLICT/);
  assert.match(source, /publishedAt: existingFirstAt/);
});

test('previous client-only publication cannot retroactively mint first-publication XP', () => {
  assert.match(source, /store\.get\('publicationStatus'\) === 'published'/);
  assert.match(source, /listing\.get\('publicationStatus'\) === 'published'/);
  assert.match(source, /FIRST_STORE_PUBLICATION_PREEXISTING_UNVERIFIED/);
});

test('publication timestamp is generated by server, never accepted from browser', () => {
  assert.match(source, /const publishedAt = new Date\(\)\.toISOString\(\)/);
  assert.doesNotMatch(source, /input: \{[^}]*publishedAt/);
});

test('replay requires full verified event identity and matching marketplace timestamp', () => {
  assert.match(source, /event\.get\('id'\) !== FIRST_STORE_PUBLISHED_CHALLENGE_ID/);
  assert.match(source, /!\['pending', 'unrewarded'\]\.includes\(event\.get\('status'\)\)/);
  assert.match(source, /event\.get\('isFirstPublication'\) !== true/);
  assert.match(source, /listing\.get\('publishedAt'\) !== existingFirstAt/);
});


test('unrewarded first publication remains idempotent and cannot mint XP later', () => {
  assert.match(source, /event\.get\('status'\) === 'unrewarded'/);
  assert.match(source, /xp: 0/);
  assert.match(source, /status: eligible \? 'pending' : 'unrewarded'/);
});


test('Publish uses authenticated server authority behind an opt-in browser flag', () => {
  assert.match(modal, /VITE_KYRUB_FIRST_STORE_PUBLICATION_SERVER_ENABLED/);
  assert.match(modal, /privateStore\.data\(\)\?\.canonicalStoreId/);
  assert.match(modal, /user\.getIdToken\(\)/);
  assert.match(modal, /transport=first-store-publication/);
  assert.match(modal, /if \(!response\.ok\) throw/);
  assert.match(modal, /else \{\s*await setStoreMarketplacePublication\(user, saveResult\.store, targetPublished\)/);
});


test('browser cannot forge first-store creation or publication markers in canonical store', () => {
  assert.match(canonicalRules, /!incoming\(\)\.keys\(\)\.hasAny\(\['firstStoreCreationVerified', 'firstPublishedAt'\]\)/);
  assert.match(canonicalRules, /!incoming\(\)\.diff\(existing\(\)\)\.affectedKeys\(\)\.hasAny\(\[\s*'firstStoreCreationVerified', 'firstPublishedAt'/);
});


test('saving verified store profile cannot use legacy publication refresh that resets publishedAt', () => {
  assert.match(modal, /trustedPublication = typeof canonicalSnapshot\.data\(\)\?\.firstPublishedAt === 'string'/);
  assert.match(modal, /if \(trustedPublication\) \{[\s\S]*?action: 'sync-profile'[\s\S]*?\} else \{\s*await setStoreMarketplacePublication\(user, storeToSave, true\)/);
});


test('verified profile sync is gated and never falls back to timestamp-mutating legacy update', () => {
  assert.match(modal, /trustedPublication && import\.meta\.env\.VITE_KYRUB_FIRST_STORE_PUBLICATION_SERVER_ENABLED === 'true'/);
  assert.match(modal, /else if \(trustedPublication\) \{\s*marketplaceSynced = false;/);
});
