import assert from 'node:assert/strict';
import {test,after} from 'node:test';
import {randomBytes,createHash} from 'node:crypto';
import {initializeApp,getApps,deleteApp} from 'firebase-admin/app';
import {getFirestore} from 'firebase-admin/firestore';
import {getAuth} from 'firebase-admin/auth';
import {assertPrivacyEmulator,PRIVACY_EMULATOR_PROJECT,createPrivacyRightsEmulator} from '../server/governance/privacyRightsEmulator';
import {createPrivacyRightsAdminEmulator} from '../server/governance/privacyRightsAdminEmulator';
assertPrivacyEmulator();
const app=initializeApp({projectId:PRIVACY_EMULATOR_PROJECT},'privacy-test-fixtures'),db=getFirestore(app);
const random=()=>randomBytes(32).toString('base64url'),hash=(s:string)=>createHash('sha256').update(s).digest('hex');
after(async()=>{for(const a of getApps().filter(a=>['privacy-test-fixtures','privacy-rights-local-emulator','privacy-admin-local-emulator'].includes(a.name)))await deleteApp(a);});
test('private intake is idempotent and administrative review cannot execute rights',async()=>{
 const now=Date.now(),credential={id:random(),secret:random()},requestId=random();
 const channel=db.collection('privacy_emulator_channels').doc(credential.id);
 await channel.set({id:credential.id,digest:hash(credential.secret),verifiedAt:now-1000,expiresAt:now+600000,simulation:true});
 const intake=createPrivacyRightsEmulator(),draft={right:'access',context:'thirdParty',confirmed:true};
 await assert.rejects(intake.submit({...credential,secret:random()},requestId,draft,now));
 const results=await Promise.all([intake.submit(credential,requestId,draft,now),intake.submit(credential,requestId,draft,now)]);
 assert.equal(results[0].protocol,results[1].protocol);
 assert.equal((await db.collection('privacy_emulator_requests').get()).size,1);
 assert.ok(!JSON.stringify(results).includes(credential.id));
 await assert.rejects(intake.submit(credential,requestId,{...draft,right:'correction'},now));
 await channel.update({revokedAt:now});await assert.rejects(intake.submit(credential,requestId,draft,now+1));
 const auth=getAuth(app),uid='privacy-fixture-admin',email='privacy-fixture@example.invalid',password='LocalFixturePassword123!';
 await auth.createUser({uid,email,password,emailVerified:true});
 const response=await fetch('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signInWithPassword?key=demo-key',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email,password,returnSecureToken:true})});
 assert.equal(response.status,200);
 const {idToken}=await response.json() as {idToken:string};
 const clock=()=>Date.now()+1000,admin=createPrivacyRightsAdminEmulator();
 const profile=db.doc('kyrub_admin/control_plane/admins/'+uid),grant=db.doc('kyrub_admin/control_plane/privacy_rights_grants/'+uid);
 await profile.set({uid,role:'compliance',status:'active'});
 await assert.rejects(admin.list(idToken,clock()));
 await grant.set({uid,status:'active',permissions:['privacy:read']});
 const list=await admin.list(idToken,clock());assert.equal(list.items.length,1);assert.ok(!JSON.stringify(list).includes(credential.id));
 const input={protocol:results[0].protocol,expectedRevision:0};
 await assert.rejects(admin.markVerificationRequired(idToken,input,clock()));
 await grant.update({permissions:['privacy:read','privacy:triage']});
 await assert.rejects(admin.markVerificationRequired(idToken,{...input,execute:true},clock()));
 const decisions=await Promise.allSettled([admin.markVerificationRequired(idToken,input,clock()),admin.markVerificationRequired(idToken,input,clock())]);
 assert.equal(decisions.filter(x=>x.status==='fulfilled').length,1);
 const state=(await db.collection('privacy_emulator_requests').doc(input.protocol).get()).data();
 assert.equal(state?.triageStatus,'verification-required');assert.equal(state?.identityStatus,'pending-verification');assert.equal(state?.actionStatus,'not-executed');
 await profile.update({status:'suspended'});await assert.rejects(admin.list(idToken,clock()));
 assert.equal((await db.collection('privacy_emulator_audit').get()).size,2);
});
