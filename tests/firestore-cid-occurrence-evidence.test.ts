import assert from 'node:assert/strict';
import {test,after} from 'node:test';
import {randomBytes,createHash} from 'node:crypto';
import {initializeApp,getApps,deleteApp} from 'firebase-admin/app';
import {getFirestore} from 'firebase-admin/firestore';
import {assertCidSosEmulator,CID_EMULATOR_PROJECT,createCidSosEmulatorStore} from '../server/identity/cidSosEmulatorStore';
import {createCidChatEmulatorStore,CID_CHAT_EMULATOR_ORIGIN as origin} from '../server/identity/cidChatEmulatorStore';
import {createCidSosNotificationEmulator} from '../server/identity/cidSosNotificationEmulator';
import {prepareCidSosConfig,type ChannelGrant} from '../server/identity/cidSosPrivateConfig';
import {isolatedTagPasskeyScope,issueTagPasskeyChallenge} from '../server/identity/kyrubTagPasskeyPolicy';
import {tagRegistrationOptions,verifyTagRegistration} from '../server/identity/kyrubTagPasskeyVerifier';
import {makeSoftwareTagAuthenticator} from './fixtures/kyrub-tag-software-authenticator';
import {normalizeCidSosResolution,cidSosResolutionNotice} from '../shared/cidSosResolution';

assertCidSosEmulator();
const app=initializeApp({projectId:CID_EMULATOR_PROJECT},'cid-resolution-fixtures');
const db=getFirestore(app),now=Date.UTC(2026,10,26,12);
const tagId='a'.repeat(32),ownerId='owner-test',id='b'.repeat(32);
const tag={tagId,ownerId,displayName:'CID fictício',active:true};
const root=db.collection('cid_sos_emulator_tags').doc(tagId);
const person=(id:string)=>({id,name:id,channels:[{channel:'email',address:id+'@example.invalid'}]});
const config=prepareCidSosConfig(tag,ownerId,null,{expectedRevision:0,enabled:true,owner:person(ownerId),contacts:[person('contact-a'),person('contact-b'),person('contact-c')]});
const grants:ChannelGrant[]=[config.owner,...config.contacts].flatMap(p=>p.channels.map(c=>({...c,tagId,ownerId,participantId:p.id,verifiedAt:now-1000,consent:true})));
const hash=(x:string)=>createHash('sha256').update(x).digest('hex');
after(async()=>{for(const a of getApps().filter(a=>['cid-resolution-fixtures','cid-sos-local-emulator','cid-chat-local-emulator','cid-notification-local-emulator'].includes(a.name)))await deleteApp(a);});
test('owner alone exports complete authorized report and requests preservation',async()=>{
 await root.set({tag,revision:0});
 await root.collection('private').doc('config').set({config});
 await root.collection('private').doc('grants').set({grants});
 const scope=isolatedTagPasskeyScope(origin,origin),auth=makeSoftwareTagAuthenticator(origin,scope.rpId);
 const registration=issueTagPasskeyChallenge({tagId,purpose:'register',ownerId:null,credentialId:null,scope},now);
 const stored=await verifyTagRegistration(registration,auth.register(await tagRegistrationOptions(registration,now)),now);
 await db.collection('kyrub_official_tags').doc(tagId).set({ownerId,ownerAuthMode:'passkey',enabled:true,blocked:false});
 await db.collection('kyrub_tag_passkey_credentials').doc(tagId).set({ownerId,credential:stored});
 await db.collection('kyrub_tag_passkey_credential_index').doc(hash(stored.id)).set({ownerId,tagId});
 const emitter=await createCidSosEmulatorStore(tagId).submitEmitterAlert({id,confirmed:true,reason:'Animal encontrado',sms:false,location:{latitude:0,longitude:0,accuracy:20,consent:true}},randomBytes(32).toString('base64url'),now+1);
 const chat=createCidChatEmulatorStore(tagId,id);
 const ceremony=await chat.beginOwnerPasskey(origin,now+2),owner=await chat.finishOwnerPasskey(origin,ceremony.challengeId,auth.assert(ceremony.options),now+3);
 await assert.rejects(chat.exportOccurrence(emitter.session,'text',now+4));
 await assert.rejects(chat.preserveEvidence(emitter.session,'motivo',now+4));
 await assert.rejects(chat.send(emitter.session,{id:id+'-resolution',body:'falso'},now+4));
 await chat.send(emitter.session,{id:'msg-a',body:'Encontrei o animal.'},now+4);
 await chat.resolve(owner,'recovered',now+5);
 const structured=await chat.exportOccurrence(owner,'structured',now+6),report=JSON.parse(structured.content);
 assert.equal(report.content.messages.length,3);assert.equal(report.content.resolution,'recovered');
 assert.equal(report.content.location.accuracy,20);
 assert.equal(report.checksum,hash(JSON.stringify(report.content)));
 assert.ok(!structured.content.includes('example.invalid'));assert.ok(!structured.content.includes(owner.secret));
 const state=root.collection('occurrences').doc(id).collection('chat').doc('state'),issued=state.collection('issuedReports');
 const receipt=(await issued.doc(structured.reportId).get()).data()!;
 assert.equal(receipt.checksum,report.checksum);assert.equal(receipt.fileChecksum,hash(structured.content));assert.equal(receipt.simulation,true);
 const txt=await chat.exportOccurrence(owner,'text',now+7);
 assert.match(txt.content,/Objeto recuperado/);assert.match(txt.content,/Encontrei o animal/);assert.match(txt.content,/Localização voluntária/);
 assert.equal((await issued.get()).size,2);
 await assert.rejects(chat.preserveEvidence(owner,' ',now+8));
 const requests=await Promise.all([chat.preserveEvidence(owner,'Preservar conversa',now+8),chat.preserveEvidence(owner,'Preservar conversa',now+8)]);
 assert.equal(requests[0].id,requests[1].id);assert.equal(requests.filter(x=>x.duplicate).length,1);
 assert.equal(requests[0].status,'pending-review');
 const persisted=(await state.collection('private').doc('preservation-request').get()).data()!;
 assert.equal(persisted.request.status,'pending-review');assert.equal(persisted.simulation,true);
 await assert.rejects(chat.preserveEvidence(owner,'outro motivo',now+9));
 await chat.revokeOwnSession(owner,now+10);
 await assert.rejects(chat.exportOccurrence(owner,'text',now+11));
 await assert.rejects(chat.preserveEvidence(owner,'Preservar conversa',now+11));
});
