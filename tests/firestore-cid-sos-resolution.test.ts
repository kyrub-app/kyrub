import assert from 'node:assert/strict';
import {test,after} from 'node:test';
import {randomBytes,createHash} from 'node:crypto';
import {initializeApp,getApps,deleteApp} from 'firebase-admin/app';
import {getFirestore} from 'firebase-admin/firestore';
import {assertCidSosEmulator,CID_EMULATOR_PROJECT,createCidSosEmulatorStore} from '../server/identity/cidSosEmulatorStore';
import {createCidChatEmulatorStore,CID_CHAT_EMULATOR_ORIGIN as origin} from '../server/identity/cidChatEmulatorStore';
import {createCidSosNotificationEmulator} from '../server/identity/cidSosNotificationEmulator';
import {prepareCidSosConfig,type ChannelGrant} from '../server/identity/cidSosPrivateConfig';
import {isolatedTagPasskeyScope,issueTagPasskeyChallenge} from '../server/identity/kyrubTagPasskeyPolicy';
import {tagRegistrationOptions,verifyTagRegistration} from '../server/identity/kyrubTagPasskeyVerifier';
import {makeSoftwareTagAuthenticator} from './fixtures/kyrub-tag-software-authenticator';
import {normalizeCidSosResolution,cidSosResolutionNotice} from '../shared/cidSosResolution';

assertCidSosEmulator();
const app=initializeApp({projectId:CID_EMULATOR_PROJECT},'cid-resolution-fixtures');
const db=getFirestore(app),now=Date.UTC(2026,10,26,12);
const tagId='a'.repeat(32),ownerId='owner-test',id='b'.repeat(32);
const tag={tagId,ownerId,displayName:'CID fictício',active:true};
const root=db.collection('cid_sos_emulator_tags').doc(tagId);
const person=(id:string)=>({id,name:id,channels:[{channel:'email',address:id+'@example.invalid'}]});
const config=prepareCidSosConfig(tag,ownerId,null,{expectedRevision:0,enabled:true,owner:person(ownerId),contacts:[person('contact-a'),person('contact-b'),person('contact-c')]});
const grants:ChannelGrant[]=[config.owner,...config.contacts].flatMap(p=>p.channels.map(c=>({...c,tagId,ownerId,participantId:p.id,verifiedAt:now-1000,consent:true})));
const hash=(x:string)=>createHash('sha256').update(x).digest('hex');
after(async()=>{for(const a of getApps().filter(a=>['cid-resolution-fixtures','cid-sos-local-emulator','cid-chat-local-emulator','cid-notification-local-emulator'].includes(a.name)))await deleteApp(a);});
test('only authenticated owner resolves atomically and notifies eligible previously delivered contacts',async()=>{
 for(const [key,label] of [['safe','Estou bem'],['misuse','Acionamento indevido'],['recovered','Objeto recuperado']] as const)assert.ok(cidSosResolutionNotice(normalizeCidSosResolution(key)).includes(label));
 assert.throws(()=>normalizeCidSosResolution('other'));
 await root.set({tag,revision:0});
 await root.collection('private').doc('config').set({config});
 const grantRef=root.collection('private').doc('grants');await grantRef.set({grants});
 const scope=isolatedTagPasskeyScope(origin,origin),auth=makeSoftwareTagAuthenticator(origin,scope.rpId);
 const record=issueTagPasskeyChallenge({tagId,purpose:'register',ownerId:null,credentialId:null,scope},now);
 const registration=await tagRegistrationOptions(record,now);
 const stored=await verifyTagRegistration(record,auth.register(registration),now);
 await db.collection('kyrub_official_tags').doc(tagId).set({ownerId,ownerAuthMode:'passkey',enabled:true,blocked:false});
 await db.collection('kyrub_tag_passkey_credentials').doc(tagId).set({ownerId,credential:stored});
 await db.collection('kyrub_tag_passkey_credential_index').doc(hash(stored.id)).set({ownerId,tagId});
 const emitter=await createCidSosEmulatorStore(tagId).submitEmitterAlert({id,confirmed:true,reason:'Animal encontrado',sms:false},randomBytes(32).toString('base64url'),now+1);
 const chat=createCidChatEmulatorStore(tagId,id),worker=createCidSosNotificationEmulator(tagId);
 const ceremony=await chat.beginOwnerPasskey(origin,now+2);
 const owner=await chat.finishOwnerPasskey(origin,ceremony.challengeId,auth.assert(ceremony.options),now+3);
 for(const i of [0,1,2])await worker.process(id+':alert:'+i,'accepted',now+4);
 await grantRef.set({grants:grants.map(g=>g.participantId==='contact-b'?{...g,revokedAt:now+5}:g)});
 await assert.rejects(chat.resolve(emitter.session,'safe',now+6));
 await assert.rejects(chat.resolve(owner,'invalid',now+6));
 const result=await Promise.all([chat.resolve(owner,'recovered',now+7),chat.resolve(owner,'recovered',now+7)]);
 assert.equal(result.filter(r=>r.duplicate).length,1);
 assert.equal(result.reduce((n,r)=>n+r.queued,0),1);
 const occurrence=root.collection('occurrences').doc(id),state=occurrence.collection('chat').doc('state'),outbox=root.collection('outbox');
 assert.equal((await occurrence.get()).get('status'),'resolved');
 assert.equal((await occurrence.get()).get('resolution'),'recovered');
 assert.equal((await state.get()).get('closedAt'),now+7);
 assert.equal((await state.collection('messages').get()).size,2);
 const view=await chat.read(emitter.session,now+8);
 assert.equal(view.resolution,'recovered');
 assert.equal(view.closed,true);
 assert.ok(view.messages.some(m=>m.body.includes('Objeto recuperado')));
 await assert.rejects(chat.resolve(owner,'safe',now+8));
 await assert.rejects(chat.send(emitter.session,{id:'late',body:'texto'},now+8));
 assert.equal((await outbox.get()).size,5);
 assert.equal((await outbox.doc(hash(id+':alert:3')).get()).get('status'),'simulation-cancelled');
 assert.equal((await outbox.doc(hash(id+':resolution:1')).get()).get('message.recipient.participantId'),'contact-a');
 assert.equal((await worker.process(id+':resolution:1','accepted',now+9)).status,'simulation-delivered');
 assert.equal((await worker.process(id+':resolution:1','accepted',now+9)).duplicate,true);
 assert.equal((await worker.process(id+':alert:3','accepted',now+9)).status,'simulation-cancelled');
});
