import assert from 'node:assert/strict';
import {test} from 'node:test';
import {createHash} from 'node:crypto';
import {mkdtempSync,readFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {execFileSync} from 'node:child_process';
import {createServer} from 'node:https';
import {initializeApp,getApps,deleteApp} from 'firebase-admin/app';
import {getFirestore} from 'firebase-admin/firestore';
import {createServer as createViteServer} from 'vite';
import tailwindcss from '@tailwindcss/vite';
import {chromium} from 'playwright';
import {assertCidSosEmulator,CID_EMULATOR_PROJECT} from '../server/identity/cidSosEmulatorStore.ts';
import {createCidChatEmulatorStore,CID_CHAT_EMULATOR_ORIGIN as origin} from '../server/identity/cidChatEmulatorStore.ts';
import {createCidSosHttpEmulatorHandler} from '../server/identity/cidSosHttpEmulator.ts';
import {prepareCidSosConfig} from '../server/identity/cidSosPrivateConfig.ts';
import {isolatedTagPasskeyScope,issueTagPasskeyChallenge} from '../server/identity/kyrubTagPasskeyPolicy.ts';
import {tagRegistrationOptions,verifyTagRegistration} from '../server/identity/kyrubTagPasskeyVerifier.ts';

test('Chromium SOS: three private cookie jars, real WebAuthn ceremony and local Firestore',{timeout:180000},async()=>{
 assertCidSosEmulator();
 const app=initializeApp({projectId:CID_EMULATOR_PROJECT},'cid-browser-fixtures');
 const db=getFirestore(app),tagId='a'.repeat(32),ownerId='owner-test',now=Date.now();
 const tag={tagId,ownerId,displayName:'CID fictício',active:true};
 const root=db.collection('cid_sos_emulator_tags').doc(tagId);
 const person=id=>({id,name:id,channels:[{channel:'email',address:id+'@example.invalid'}]});
 const config=prepareCidSosConfig(tag,ownerId,null,{expectedRevision:0,enabled:true,owner:person(ownerId),contacts:[person('contact-test')]});
 const grants=[config.owner,...config.contacts].flatMap(p=>p.channels.map(c=>({...c,tagId,ownerId,participantId:p.id,verifiedAt:now-1000,consent:true})));
 const folder=mkdtempSync(join(tmpdir(),'cid-browser-')),key=join(folder,'key.pem'),cert=join(folder,'cert.pem');
 let vite,server,browser,confirmation='';
 const errors=[],external=[];
 try{
  await root.set({tag,revision:0});
  await root.collection('private').doc('config').set({config});
  await root.collection('private').doc('grants').set({grants});
  execFileSync('openssl',['req','-x509','-newkey','rsa:2048','-nodes','-keyout',key,'-out',cert,'-days','1','-subj','/CN=kyrub-cid-emulator.vercel.app','-addext','subjectAltName=DNS:kyrub-cid-emulator.vercel.app'],{stdio:'ignore'});
  vite=await createViteServer({configFile:false,plugins:[tailwindcss()],appType:'custom',server:{middlewareMode:true,hmr:false,allowedHosts:['kyrub-cid-emulator.vercel.app']},esbuild:{jsx:'automatic'}});
  const handler=createCidSosHttpEmulatorHandler(async envelope=>{assert.equal(envelope.route.address,'contact-test@example.invalid');confirmation=envelope.secret;});
  server=createServer({key:readFileSync(key),cert:readFileSync(cert)},(req,res)=>{
   if(req.url?.startsWith('/cid-homologation/api/'))return void handler(req,res);
   if(req.method==='GET'&&req.url?.startsWith('/cid-test/')){
    void vite.transformIndexHtml(req.url,'<!doctype html><html lang="pt-BR"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"></head><body><div id="root"></div><script type="module" src="/tests/fixtures/cid-sos-browser.tsx"></script></body></html>').then(html=>{res.setHeader('Content-Type','text/html; charset=utf-8');res.end(html);},()=>{res.statusCode=500;res.end();});return;
   }
   vite.middlewares(req,res,()=>{res.statusCode=404;res.end();});
  });
  await new Promise((resolve,reject)=>{server.once('error',reject);server.listen(0,'127.0.0.1',resolve);});
  browser=await chromium.launch({headless:true,args:['--no-proxy-server','--host-resolver-rules=MAP kyrub-cid-emulator.vercel.app 127.0.0.1:'+server.address().port+', MAP * ~NOTFOUND']});
  async function device(){
   const ctx=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:390,height:844},serviceWorkers:'block'});
   await ctx.route('**/*',route=>{const u=new URL(route.request().url());if(u.origin===origin)return route.continue();external.push(u.origin);return route.abort();});
   const page=await ctx.newPage();page.on('pageerror',e=>errors.push(e.message));
   return {ctx,page};
  }
  const owner=await device(),emitter=await device(),contact=await device();
  const cdp=await owner.ctx.newCDPSession(owner.page);
  await cdp.send('WebAuthn.enable');
  await cdp.send('WebAuthn.addVirtualAuthenticator',{options:{protocol:'ctap2',transport:'internal',hasResidentKey:true,hasUserVerification:true,isUserVerified:true,automaticPresenceSimulation:true}});
  await owner.page.goto(origin+'/cid-test/'+tagId+'/register');
  await owner.page.waitForFunction(()=>typeof window.cidTestRegister==='function');
  const scope=isolatedTagPasskeyScope(origin,origin);
  const record=issueTagPasskeyChallenge({tagId,purpose:'register',ownerId:null,credentialId:null,scope},Date.now());
  const options=await tagRegistrationOptions(record);
  const registration=await owner.page.evaluate(options=>window.cidTestRegister(options),options);
  const credential=await verifyTagRegistration(record,registration);
  await db.collection('kyrub_official_tags').doc(tagId).set({ownerId,ownerAuthMode:'passkey',enabled:true,blocked:false});
  await db.collection('kyrub_tag_passkey_credentials').doc(tagId).set({ownerId,credential});
  await db.collection('kyrub_tag_passkey_credential_index').doc(createHash('sha256').update(credential.id).digest('hex')).set({ownerId,tagId});
  const p=emitter.page;
  await p.goto(origin+'/cid-test/'+tagId+'/emitter');
  await p.getByRole('button',{name:'Emitir alerta',exact:true}).click();
  assert.equal((await root.collection('occurrences').get()).size,0);
  await p.getByLabel('Motivo do alerta').fill('Animal encontrado');
  await p.getByRole('button',{name:'Simular emissão do alerta'}).click();
  await p.getByRole('region',{name:'Chat da ocorrência'}).waitFor();
  const records=await root.collection('occurrences').get();assert.equal(records.size,1);
  const id=records.docs[0].id,api='/cid-homologation/api/'+tagId+'/'+id+'/';
  const cookie=(await emitter.ctx.cookies(origin+api+'read')).find(c=>c.name==='__Secure-cid-homologation');
  assert.ok(cookie&&cookie.httpOnly&&cookie.secure&&cookie.sameSite==='Strict');assert.equal(cookie.path,api);
  assert.ok(!(await p.evaluate(()=>document.cookie)).includes('__Secure-cid-homologation'));
  assert.equal((await owner.ctx.cookies(origin+api+'read')).length,0);
  const status=await owner.page.evaluate(async path=>(await fetch(path,{method:'POST',headers:{'Content-Type':'application/json','X-Cid-Homologation':'1'},body:'{}'})).status,api+'read');
  assert.equal(status,403);
  await p.getByLabel('Mensagem',{exact:true}).fill('Encontrei o animal.');
  await p.getByRole('button',{name:'Enviar mensagem'}).click();
  await p.getByRole('log').getByText('Encontrei o animal.',{exact:true}).waitFor();
  await owner.page.goto(origin+'/cid-test/'+tagId+'/owner/'+id);
  await owner.page.getByRole('button',{name:'Acessar ocorrência por passkey'}).click();
  await owner.page.getByRole('log').getByText('Encontrei o animal.',{exact:true}).waitFor();
  const chat=createCidChatEmulatorStore(tagId,id);
  const delivered=await chat.prepareContactInvitationForDelivery('contact-test','email',Date.now());
  await contact.page.goto(origin+'/cid-test/'+tagId+'/contact/'+id+'#'+delivered.invitation.id+'.'+delivered.invitation.secret);
  await contact.page.getByRole('button',{name:'Solicitar confirmação do contato'}).click();
  await contact.page.getByLabel('Confirmação do contato').waitFor();
  assert.equal(new URL(contact.page.url()).hash,'');assert.ok(confirmation);
  assert.ok(!(await contact.page.locator('body').innerText()).includes(confirmation));
  await contact.page.getByLabel('Confirmação do contato').fill(confirmation);
  await contact.page.getByRole('button',{name:'Confirmar acesso'}).click();
  await contact.page.getByRole('log').waitFor();
  await contact.page.getByLabel('Mensagem',{exact:true}).fill('Estou acompanhando.');
  await contact.page.getByRole('button',{name:'Enviar mensagem'}).click();
  await contact.page.getByRole('log').getByText('Estou acompanhando.',{exact:true}).waitFor();
  await owner.page.getByRole('button',{name:'Atualizar conversa'}).click();
  await owner.page.getByRole('log').getByText('Estou acompanhando.',{exact:true}).waitFor();
  await owner.page.screenshot({path:'cid-sos-browser-chat.png',fullPage:true});
  await owner.page.getByRole('button',{name:'Opções da ocorrência'}).click();
  await owner.page.getByRole('button',{name:'Encerrar ocorrência',exact:true}).click();
  await owner.page.getByRole('button',{name:'Confirmar encerramento'}).click();
  await owner.page.getByText('Ocorrência encerrada.',{exact:false}).waitFor();
  await p.getByRole('button',{name:'Atualizar conversa'}).click();
  await p.getByText('Ocorrência encerrada.',{exact:false}).waitFor();
  await contact.page.getByRole('button',{name:'Voltar'}).click();
  await contact.page.getByRole('region',{name:'Chat da ocorrência'}).waitFor({state:'hidden'});
  await contact.page.waitForFunction(async path=>(await fetch(path,{method:'POST',headers:{'Content-Type':'application/json','X-Cid-Homologation':'1'},body:'{}'})).status===403,api+'read');
  assert.equal((await root.collection('outbox').get()).size,2);
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  console.info('CID_BROWSER: TLS loopback, independent cookie jars, virtual WebAuthn registration and authentication, contact confirmation, persisted messages and close/revoke; zero external requests.');
 }finally{await browser?.close();if(server)await new Promise(r=>server.close(r));await vite?.close();rmSync(folder,{recursive:true,force:true});for(const a of getApps().filter(a=>['cid-browser-fixtures','cid-sos-local-emulator','cid-chat-local-emulator'].includes(a.name)))await deleteApp(a);}
});
