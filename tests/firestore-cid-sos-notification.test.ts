import assert from 'node:assert/strict';
import {test,after} from 'node:test';
import {randomBytes} from 'node:crypto';
import {initializeApp,getApps,deleteApp} from 'firebase-admin/app';
import {getFirestore} from 'firebase-admin/firestore';
import {assertCidSosEmulator,CID_EMULATOR_PROJECT,createCidSosEmulatorStore} from '../server/identity/cidSosEmulatorStore';
import {createCidSosNotificationEmulator} from '../server/identity/cidSosNotificationEmulator';
import {prepareCidSosConfig,type ChannelGrant} from '../server/identity/cidSosPrivateConfig';
assertCidSosEmulator();
const app=initializeApp({projectId:CID_EMULATOR_PROJECT},'cid-notification-fixtures');
const db=getFirestore(app),now=Date.UTC(2026,10,26,12);
const tag={tagId:'a'.repeat(32),ownerId:'owner-test',displayName:'CID fictício',active:true};
const root=db.collection('cid_sos_emulator_tags').doc(tag.tagId);
const person=(id:string,n:number)=>({id,name:id,channels:[{channel:'email',address:id+'@example.invalid'},{channel:'whatsapp',address:'+551199999000'+n},{channel:'sms',address:'+551199999000'+n}]});
const config=prepareCidSosConfig(tag,tag.ownerId,null,{expectedRevision:0,enabled:true,owner:person(tag.ownerId,1),contacts:[person('contact-a',2)]});
const grants:ChannelGrant[]=[config.owner,...config.contacts].flatMap(p=>p.channels.map(c=>({...c,tagId:tag.tagId,ownerId:tag.ownerId,participantId:p.id,verifiedAt:now-1000,consent:true})));
after(async()=>{for(const a of getApps().filter(a=>['cid-notification-fixtures','cid-sos-local-emulator','cid-notification-local-emulator'].includes(a.name)))await deleteApp(a);});
test('simulated queue handles all channels, deduplicates processing and rechecks consent',async()=>{
 await root.set({tag,revision:0});
 await root.collection('private').doc('config').set({config});
 const grantRef=root.collection('private').doc('grants');await grantRef.set({grants});
 const id='b'.repeat(32),sos=createCidSosEmulatorStore(tag.tagId);
 await sos.submitEmitterAlert({id,confirmed:true,reason:'Motivo privado',sms:true},randomBytes(32).toString('base64url'),now);
 const worker=createCidSosNotificationEmulator(tag.tagId);
 const key=(n:number)=>id+':alert:'+n;
 const results=await Promise.all([worker.process(key(0),'accepted',now+1),worker.process(key(0),'accepted',now+1)]);
 assert.equal(results.filter(r=>r.duplicate).length,1);
 assert.equal(results[0].status,'simulation-delivered');
 assert.equal((await worker.process(key(1),'retryable',now+2)).status,'simulation-retry');
 assert.equal((await worker.process(key(1),'accepted',now+3)).duplicate,true);
 assert.equal((await worker.process(key(1),'retryable',now+60002)).attempts,2);
 assert.equal((await worker.process(key(1),'retryable',now+120002)).status,'simulation-failed');
 assert.equal((await worker.process(key(2),'accepted',now+4)).status,'simulation-delivered');
 assert.equal((await worker.process(key(3),'rejected',now+5)).status,'simulation-failed');
 await grantRef.set({grants:grants.map(g=>g.participantId==='contact-a'&&g.channel==='whatsapp'?{...g,revokedAt:now+6}:g)});
 assert.equal((await worker.process(key(4),'accepted',now+7)).status,'simulation-cancelled');
 assert.equal((await worker.process(key(5),'accepted',now+1800000)).status,'simulation-cancelled');
 const rows=(await root.collection('outbox').get()).docs.map(d=>d.data());
 assert.equal(rows.length,6);
 assert.ok(rows.some(r=>r.adapter==='mock-email')&&rows.some(r=>r.adapter==='mock-whatsapp')&&rows.some(r=>r.adapter==='mock-sms'));
 assert.ok(rows.every(r=>r.status.startsWith('simulation-')));
 assert.ok(!JSON.stringify(rows).includes('Motivo privado'));
 assert.equal((await root.collection('occurrences').get()).size,1);
 await assert.rejects(createCidSosNotificationEmulator('c'.repeat(32)).process(key(0),'accepted',now+8));
});
