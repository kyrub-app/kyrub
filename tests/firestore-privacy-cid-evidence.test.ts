import assert from 'node:assert/strict';
import {test,after} from 'node:test';
import {randomBytes,createHash} from 'node:crypto';
import {initializeApp,getApps,deleteApp} from 'firebase-admin/app';
import {getFirestore} from 'firebase-admin/firestore';
import {assertPrivacyEmulator,PRIVACY_EMULATOR_PROJECT,createPrivacyRightsEmulator} from '../server/governance/privacyRightsEmulator';
import {createPrivacyCidEvidenceEmulator,PRIVACY_CID_ORIGIN as origin} from '../server/governance/privacyCidEvidenceEmulator';
import {isolatedTagPasskeyScope,issueTagPasskeyChallenge} from '../server/identity/kyrubTagPasskeyPolicy';
import {tagRegistrationOptions,verifyTagRegistration} from '../server/identity/kyrubTagPasskeyVerifier';
import {makeSoftwareTagAuthenticator} from './fixtures/kyrub-tag-software-authenticator';
assertPrivacyEmulator();
const app=initializeApp({projectId:PRIVACY_EMULATOR_PROJECT},'privacy-cid-fixtures'),db=getFirestore(app);
const random=()=>randomBytes(32).toString('base64url'),hash=(s:string)=>createHash('sha256').update(s).digest('hex');
after(async()=>{for(const a of getApps().filter(a=>['privacy-cid-fixtures','privacy-rights-local-emulator','privacy-cid-evidence-local-emulator'].includes(a.name)))await deleteApp(a);});
test('CID passkey evidence is protocol-bound, fresh and not an authorization to execute rights',async()=>{
 const now=Date.now(),tagId='a'.repeat(32),ownerId='cid-owner-fixture',scope=isolatedTagPasskeyScope(origin,origin);
 const auth=makeSoftwareTagAuthenticator(origin,scope.rpId),registration=issueTagPasskeyChallenge({tagId,purpose:'register',ownerId:null,credentialId:null,scope},now);
 const stored=await verifyTagRegistration(registration,auth.register(await tagRegistrationOptions(registration,now)),now);
 const tag=db.collection('kyrub_official_tags').doc(tagId);
 await tag.set({ownerId,ownerAuthMode:'passkey',enabled:true,blocked:false});
 await db.collection('kyrub_tag_passkey_credentials').doc(tagId).set({ownerId,credential:stored});
 await db.collection('kyrub_tag_passkey_credential_index').doc(hash(stored.id)).set({ownerId,tagId});
 const credential={id:random(),secret:random()},channel=db.collection('privacy_emulator_channels').doc(credential.id);
 await channel.set({id:credential.id,digest:hash(credential.secret),verifiedAt:now-1000,expiresAt:now+600000,simulation:true,boundTagId:tagId,boundOwnerId:ownerId});
 const intake=createPrivacyRightsEmulator(),cid=createPrivacyCidEvidenceEmulator(),draft={right:'access',context:'cid',confirmed:true};
 const receipt=await intake.submit(credential,random(),draft,now+1),other=await intake.submit(credential,random(),draft,now+1);
 const ref=db.collection('privacy_emulator_requests').doc(receipt.protocol);
 await assert.rejects(cid.begin(receipt.protocol,receipt.trackingCode,origin,now+2));
 await ref.update({triageStatus:'verification-required',revision:1});
 await db.collection('privacy_emulator_requests').doc(other.protocol).update({triageStatus:'verification-required',revision:1});
 await assert.rejects(cid.begin(receipt.protocol,random(),origin,now+2));
 await assert.rejects(cid.begin(receipt.protocol,receipt.trackingCode,'https://wrong.example',now+2));
 await channel.update({boundOwnerId:'different-owner'});
 await assert.rejects(cid.begin(receipt.protocol,receipt.trackingCode,origin,now+2));
 await channel.update({boundOwnerId:ownerId});
 const ceremony=await cid.begin(receipt.protocol,receipt.trackingCode,origin,now+3),assertion=auth.assert(ceremony.options);
 await assert.rejects(cid.finish(other.protocol,other.trackingCode,origin,ceremony.challengeId,assertion,now+4));
 await tag.update({blocked:true});
 await assert.rejects(cid.finish(receipt.protocol,receipt.trackingCode,origin,ceremony.challengeId,assertion,now+4));
 await tag.update({blocked:false});
 const result=await cid.finish(receipt.protocol,receipt.trackingCode,origin,ceremony.challengeId,assertion,now+5);
 assert.equal(result.evidenceStatus,'cid-control-confirmed');assert.equal(result.identityStatus,'pending-verification');assert.equal(result.actionStatus,'not-executed');
 await assert.rejects(cid.finish(receipt.protocol,receipt.trackingCode,origin,ceremony.challengeId,assertion,now+6));
 const tracked=await intake.track(receipt.protocol,receipt.trackingCode,now+6);
 assert.equal(tracked.evidenceStatus,'cid-control-confirmed');assert.ok(!JSON.stringify(tracked).includes(ownerId));assert.ok(!JSON.stringify(tracked).includes(tagId));
 const evidence=(await db.collection('privacy_emulator_identity_evidence').doc(receipt.protocol).get()).data();
 assert.equal(evidence?.authorizesExecution,false);assert.equal((await ref.get()).get('identityStatus'),'pending-verification');
});
