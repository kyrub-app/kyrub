import assert from 'node:assert/strict';
import {test,after} from 'node:test';
import {randomBytes} from 'node:crypto';
import {initializeApp,getApps,deleteApp} from 'firebase-admin/app';
import {getFirestore} from 'firebase-admin/firestore';
import {assertCidSosEmulator,CID_EMULATOR_PROJECT,createCidSosEmulatorStore} from '../server/identity/cidSosEmulatorStore';
import {createCidChatEmulatorStore} from '../server/identity/cidChatEmulatorStore';
import {prepareCidSosConfig,type ChannelGrant} from '../server/identity/cidSosPrivateConfig';

assertCidSosEmulator();
const app=initializeApp({projectId:CID_EMULATOR_PROJECT},'cid-contact-fixtures');
const db=getFirestore(app),now=Date.UTC(2026,10,26,12);
const tag={tagId:'a'.repeat(32),ownerId:'owner-test',displayName:'CID fictício',active:true};
const root=db.collection('cid_sos_emulator_tags').doc(tag.tagId);
const person=(id:string)=>({id,name:id,channels:[{channel:'email',address:id+'@example.invalid'}]});
const config=prepareCidSosConfig(tag,tag.ownerId,null,{expectedRevision:0,enabled:true,owner:person(tag.ownerId),contacts:[person('contact-a'),person('contact-b')]});
const grants:ChannelGrant[]=[config.owner,...config.contacts].flatMap(p=>p.channels.map(c=>({...c,tagId:tag.tagId,ownerId:tag.ownerId,participantId:p.id,verifiedAt:now-1000,consent:true})));
const request={id:'b'.repeat(32),confirmed:true,reason:'Animal encontrado',sms:false};
const token=()=>randomBytes(32).toString('base64url');
after(async()=>{for(const a of getApps().filter(a=>['cid-contact-fixtures','cid-sos-local-emulator','cid-chat-local-emulator'].includes(a.name)))await deleteApp(a);});

test('contact confirmation is separate from forwarded invitation and is checked transactionally',async()=>{
 await root.set({tag,revision:0});
 await root.collection('private').doc('config').set({config});
 const grantsRef=root.collection('private').doc('grants');
 await grantsRef.set({grants});
 await createCidSosEmulatorStore(tag.tagId).submitEmitterAlert(request,token(),now);
 const chat=createCidChatEmulatorStore(tag.tagId,request.id);
 const state=root.collection('occurrences').doc(request.id).collection('chat').doc('state');
 await assert.rejects(chat.prepareContactInvitationForDelivery('stranger','email',now));
 await assert.rejects(chat.prepareContactInvitationForDelivery('contact-a','sms',now));
 const a=await chat.prepareContactInvitationForDelivery('contact-a','email',now+1);
 const b=await chat.prepareContactInvitationForDelivery('contact-b','email',now+1);
 assert.equal(a.route.address,'contact-a@example.invalid');
 await assert.rejects(chat.prepareContactConfirmationForDelivery({...a.invitation,secret:token()},now+2));
 const challenge=await chat.prepareContactConfirmationForDelivery(a.invitation,now+2);
 assert.equal(challenge.deliveryEnvelope.route.address,a.route.address);
 assert.ok(!JSON.stringify(challenge.publicResult).includes(challenge.deliveryEnvelope.secret));
 const record=(await state.collection('contactChallenges').doc(challenge.publicResult.challengeId).get()).data()!;
 assert.ok(!JSON.stringify(record).includes(challenge.deliveryEnvelope.secret));
 await assert.rejects(chat.confirmContact(b.invitation,challenge.publicResult.challengeId,challenge.deliveryEnvelope.secret,now+3));
 await assert.rejects(chat.confirmContact(a.invitation,challenge.publicResult.challengeId,a.invitation.secret,now+3));
 assert.equal((await state.collection('contactChallenges').doc(challenge.publicResult.challengeId).get()).get('attempts'),1);
 const attempts=await Promise.allSettled([chat.confirmContact(a.invitation,challenge.publicResult.challengeId,challenge.deliveryEnvelope.secret,now+4),chat.confirmContact(a.invitation,challenge.publicResult.challengeId,challenge.deliveryEnvelope.secret,now+4)]);
 const success=attempts.filter(r=>r.status==='fulfilled');
 assert.equal(success.length,1);
 const result=success[0];assert.ok(result.status==='fulfilled');
 const session=result.value;
 assert.equal((await chat.read(session,now+5)).role,'contact');
 await chat.send(session,{id:'contact-msg',body:'Estou acompanhando.'},now+5);
 assert.equal((await state.collection('sessions').get()).size,2);
 const other=await chat.prepareContactConfirmationForDelivery(b.invitation,now+6);
 await assert.rejects(chat.confirmContact(b.invitation,other.publicResult.challengeId,other.deliveryEnvelope.secret,now+6+300000));
 await grantsRef.set({grants:grants.map(g=>g.participantId==='contact-a'||g.participantId==='contact-b'?{...g,revokedAt:now+7}:g)});
 await assert.rejects(chat.read(session,now+8));
 await assert.rejects(chat.confirmContact(b.invitation,other.publicResult.challengeId,other.deliveryEnvelope.secret,now+8));
 await assert.rejects(chat.prepareContactConfirmationForDelivery(b.invitation,now+8));
});
