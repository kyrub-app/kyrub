import assert from 'node:assert/strict';
import {test} from 'node:test';
import {createCidOccurrenceChat,issueCidChatInvite,redeemCidChatInvite,openCidChatSession,authorizeCidChatSession,prepareCidChatMessage,closeCidChat,projectCidChat,CID_CHAT_INVITE_TTL_MS,CID_CHAT_SESSION_TTL_MS} from '../server/identity/cidOccurrenceChatAccess';
import {planCidSosAlert} from '../server/identity/cidSosAlertPolicy';
const now=Date.UTC(2026,10,26,12);
const person=(id:string)=>({id,channels:[{channel:'email' as const,address:id+'@example.invalid',verifiedAt:now-1000,consent:true}]});
const profile={tagId:'a'.repeat(32),ownerId:'owner-test',displayName:'Titular de teste',active:true,enabled:true,owner:person('owner-test'),contacts:[person('contact-a'),person('contact-b'),person('contact-c')]};
const occurrence=planCidSosAlert(profile,{id:'b'.repeat(32),confirmed:true,reason:'Animal encontrado',sms:false},now,[]).occurrence;
const {chat,greeting}=createCidOccurrenceChat(occurrence,'emitter-test',now);
test('membership derived from the private occurrence; deterministic greeting; no addresses',()=>{
 assert.equal(chat.members.length,5);
 assert.equal(greeting.kind,'system');assert.equal(greeting.body,'Alerta recebido. Por favor, explique a situação.');
 assert.equal(greeting.chatId,chat.id);
 assert.ok(!JSON.stringify(chat).includes('@example.invalid'));
 assert.throws(()=>createCidOccurrenceChat(occurrence,'owner-test',now));
});
test('invitation is individual, temporary, single-use, revocable, and requires separate recipient proof',()=>{
 const a=issueCidChatInvite(chat,'contact-a',now),b=issueCidChatInvite(chat,'contact-b',now);
 assert.notEqual(a.secret,b.secret);assert.ok(!JSON.stringify(a.record).includes(a.secret));
 assert.throws(()=>issueCidChatInvite(chat,'stranger',now));
 assert.throws(()=>issueCidChatInvite(chat,'owner-test',now));
 assert.throws(()=>redeemCidChatInvite(chat,a.record,a.secret,'contact-b',now));
 assert.throws(()=>redeemCidChatInvite(chat,a.record,b.secret,'contact-a',now));
 assert.throws(()=>redeemCidChatInvite(chat,a.record,a.secret,'contact-a',now+CID_CHAT_INVITE_TTL_MS));
 assert.throws(()=>redeemCidChatInvite(chat,{...a.record,revokedAt:now},a.secret,'contact-a',now));
 const redeemed=redeemCidChatInvite(chat,a.record,a.secret,'contact-a',now+1);
 assert.equal(redeemed.invite.usedAt,now+1);
 assert.throws(()=>redeemCidChatInvite(chat,redeemed.invite,a.secret,'contact-a',now+2));
 assert.equal(authorizeCidChatSession(chat,redeemed.session.record,redeemed.session.secret,now+2,'read').role,'contact');
 assert.throws(()=>authorizeCidChatSession(chat,redeemed.session.record,redeemed.session.secret,now+2,'close'));
});
test('owner and emitter use separately verified scoped sessions; no account required',()=>{
 assert.throws(()=>openCidChatSession(chat,'owner-test','emitter-session',now));
 assert.throws(()=>openCidChatSession(chat,'contact-a','owner-passkey',now));
 const owner=openCidChatSession(chat,'owner-test','owner-passkey',now);
 const emitter=openCidChatSession(chat,'emitter-test','emitter-session',now);
 const session=emitter.record;
 assert.throws(()=>authorizeCidChatSession({...chat,id:'different'},session,emitter.secret,now,'read'));
 assert.throws(()=>authorizeCidChatSession(chat,session,owner.secret,now,'read'));
 assert.throws(()=>authorizeCidChatSession(chat,{...session,revokedAt:now},emitter.secret,now,'read'));
 assert.throws(()=>authorizeCidChatSession(chat,session,emitter.secret,now+CID_CHAT_SESSION_TTL_MS,'read'));
 const message=prepareCidChatMessage(chat,session,emitter.secret,{id:'msg-a',body:' Encontrei o animal. '},now+1);
 assert.equal(message.authorId,'emitter-test');assert.equal(message.body,'Encontrei o animal.');
 assert.throws(()=>prepareCidChatMessage(chat,session,emitter.secret,{id:'msg-b',body:'texto',authorId:'owner-test'},now));
 assert.throws(()=>prepareCidChatMessage(chat,session,emitter.secret,{id:'msg-b',body:' '},now));
 assert.throws(()=>closeCidChat(chat,session,emitter.secret,now+2));
 const closed=closeCidChat(chat,owner.record,owner.secret,now+2);
 assert.equal(closed.closedAt,now+2);
 assert.throws(()=>prepareCidChatMessage(closed,session,emitter.secret,{id:'msg-c',body:'texto'},now+3));
 assert.throws(()=>issueCidChatInvite(closed,'contact-a',now+3));
 const projected=projectCidChat(closed,owner.record,owner.secret,now+3);
 assert.equal(projected.closed,true);assert.equal(projected.participantCount,5);
 assert.match(projected.notice,/autoridades competentes/);
 assert.ok(!JSON.stringify(projected).includes(owner.record.digest));
 assert.ok(!JSON.stringify(projected).includes('contact-a'));
});
