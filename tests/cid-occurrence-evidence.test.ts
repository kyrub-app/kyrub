import assert from 'node:assert/strict';
import {test} from 'node:test';
import {createHash} from 'node:crypto';
import {planCidSosAlert} from '../server/identity/cidSosAlertPolicy';
import {createCidOccurrenceChat,openCidChatSession,prepareCidChatMessage} from '../server/identity/cidOccurrenceChatAccess';
import {prepareCidOccurrenceReport,formatCidConversationText} from '../server/identity/cidOccurrenceReport';
import {requestCidEvidencePreservation,planRestrictedEvidenceAccess,type ReviewedEvidenceCase,type VerifiedEvidenceOperator} from '../server/identity/cidEvidencePreservation';
const now=Date.UTC(2026,10,26,12);
const participant=(id:string)=>({id,channels:[{channel:'email' as const,address:id+'@example.invalid',verifiedAt:now-1000,consent:true}]});
const profile={tagId:'a'.repeat(32),ownerId:'owner-test',displayName:'Teste',active:true,enabled:true,owner:participant('owner-test'),contacts:[participant('contact-test')]};
const occurrence=planCidSosAlert(profile,{id:'b'.repeat(32),confirmed:true,reason:'Animal encontrado',sms:false,location:{latitude:0,longitude:0,accuracy:20,consent:true}},now,[]).occurrence;
const {chat,greeting}=createCidOccurrenceChat(occurrence,'emitter-test',now);
const owner=openCidChatSession(chat,'owner-test','owner-passkey',now),emitter=openCidChatSession(chat,'emitter-test','emitter-session',now);
const message=prepareCidChatMessage(chat,emitter.record,emitter.secret,{id:'msg-a',body:'Encontrei o animal.'},now+1);
test('owner export includes authorized messages and location, not recipient addresses or technical credentials',()=>{
 const report=prepareCidOccurrenceReport(chat,owner.record,owner.secret,occurrence,[message,greeting],now+2);
 assert.deepEqual(report.content.messages.map(m=>m.author),['Sistema','Emissor do alerta']);
 assert.equal(report.content.location?.accuracy,20);
 assert.equal(report.checksum,createHash('sha256').update(JSON.stringify(report.content),'utf8').digest('hex'));
 assert.ok(!JSON.stringify(report).includes('@example.invalid'));
 assert.ok(!JSON.stringify(report).includes(owner.record.digest));
 assert.ok(!JSON.stringify(report).includes('emitter-test'));
 assert.match(formatCidConversationText(report),/Encontrei o animal/);
 assert.throws(()=>prepareCidOccurrenceReport(chat,emitter.record,emitter.secret,occurrence,[message],now+2));
 assert.throws(()=>prepareCidOccurrenceReport(chat,owner.record,owner.secret,{...occurrence,id:'other'},[message],now+2));
 assert.throws(()=>prepareCidOccurrenceReport(chat,owner.record,owner.secret,occurrence,[{...message,chatId:'other'}],now+2));
 assert.throws(()=>prepareCidOccurrenceReport(chat,owner.record,owner.secret,occurrence,[message,message],now+2));
});
test('preservation request is pending review and confers no technical access',()=>{
 const request=requestCidEvidencePreservation(chat,owner.record,owner.secret,'Preservar ocorrência',now+2);
 assert.equal(request.status,'pending-review');
 assert.throws(()=>requestCidEvidencePreservation(chat,emitter.record,emitter.secret,'Preservar ocorrência',now+2));
 const review:ReviewedEvidenceCase={id:'case-test',occurrenceId:chat.id,status:'approved',purpose:'authority-disclosure',reviewedAt:now,expiresAt:now+600000,allowedFields:['connectionTime'],authorizedActorId:'officer-test'};
 const actor:VerifiedEvidenceOperator={id:'officer-test',role:'evidence-officer',recentAuthenticationAt:now};
 const plan=planRestrictedEvidenceAccess(review,actor,chat.id,['connectionTime'],now+1);
 assert.equal(plan.requiresAudit,true);
 assert.throws(()=>planRestrictedEvidenceAccess(review,actor,chat.id,['sourceIp'],now+1));
 assert.throws(()=>planRestrictedEvidenceAccess({...review,purpose:'preservation'},actor,chat.id,['connectionTime'],now+1));
 assert.throws(()=>planRestrictedEvidenceAccess({...review,status:'revoked'},actor,chat.id,['connectionTime'],now+1));
 assert.throws(()=>planRestrictedEvidenceAccess(review,{...actor,id:'other'},chat.id,['connectionTime'],now+1));
 assert.throws(()=>planRestrictedEvidenceAccess(review,actor,'other',['connectionTime'],now+1));
 assert.throws(()=>planRestrictedEvidenceAccess(review,actor,chat.id,['connectionTime'],now+300001));
});
