import assert from 'node:assert/strict';
import {test,after} from 'node:test';
import {createHash,randomBytes} from 'node:crypto';
import {initializeApp,getApps,deleteApp} from 'firebase-admin/app';
import {getFirestore} from 'firebase-admin/firestore';
import {assertCidSosEmulator,CID_EMULATOR_PROJECT} from '../server/identity/cidSosEmulatorStore';
import {createCidChatEmulatorStore,CID_CHAT_EMULATOR_ORIGIN as origin} from '../server/identity/cidChatEmulatorStore';
import {isolatedTagPasskeyScope,issueTagPasskeyChallenge} from '../server/identity/kyrubTagPasskeyPolicy';
import {tagRegistrationOptions,verifyTagRegistration} from '../server/identity/kyrubTagPasskeyVerifier';
import {createCidOccurrenceChat} from '../server/identity/cidOccurrenceChatAccess';
import {planCidSosAlert} from '../server/identity/cidSosAlertPolicy';
import {makeSoftwareTagAuthenticator} from './fixtures/kyrub-tag-software-authenticator';

assertCidSosEmulator();
const app=initializeApp({projectId:CID_EMULATOR_PROJECT},'cid-owner-passkey-fixtures');
const db=getFirestore(app);
const now=Date.UTC(2026,10,26,12);
const tagId='e'.repeat(32),occurrenceId='f'.repeat(32);
const ownerId='tagpk_'+randomBytes(32).toString('base64url');
const scope=isolatedTagPasskeyScope(origin,origin);
const participant=(id:string)=>({id,channels:[{channel:'email' as const,address:id+'@example.invalid',verifiedAt:now-1000,consent:true}]});
const profile={tagId,ownerId,displayName:'CID fictício',active:true,enabled:true,owner:participant(ownerId),contacts:[participant('contact-test')]};
const occurrence=planCidSosAlert(profile,{id:occurrenceId,confirmed:true,reason:'Animal encontrado',sms:false},now,[]).occurrence;
const liveTag=db.collection('kyrub_official_tags').doc(tagId),liveCredential=db.collection('kyrub_tag_passkey_credentials').doc(tagId);
const occurrenceRef=db.collection('cid_sos_emulator_tags').doc(tagId).collection('occurrences').doc(occurrenceId);
const root=occurrenceRef.collection('chat').doc('state');
const index=(id:string)=>db.collection('kyrub_tag_passkey_credential_index').doc(createHash('sha256').update(id).digest('hex'));
after(async()=>{for(const candidate of getApps().filter(a=>a.name==='cid-owner-passkey-fixtures'||a.name==='cid-chat-local-emulator'))await deleteApp(candidate);});
test('real WebAuthn signatures establish private owner session without a Kyrub account',async()=>{
 const authenticator=makeSoftwareTagAuthenticator(origin,scope.rpId);
 const foreign=makeSoftwareTagAuthenticator(origin,scope.rpId);
 const registration=issueTagPasskeyChallenge({tagId,purpose:'register',ownerId:null,credentialId:null,scope},now);
 const options=await tagRegistrationOptions(registration,now);
 const stored=await verifyTagRegistration(registration,authenticator.register(options),now);
 await liveTag.set({ownerId,ownerAuthMode:'passkey',enabled:true,blocked:false});
 await liveCredential.set({ownerId,credential:stored});
 await index(stored.id).set({tagId,ownerId});
 await occurrenceRef.set(occurrence);
 const {chat,greeting}=createCidOccurrenceChat(occurrence,'emitter-test',now);
 await root.set(chat);await root.collection('messages').doc(greeting.id).set(greeting);
 const store=createCidChatEmulatorStore(tagId,occurrenceId);
 await assert.rejects(store.beginOwnerPasskey('https://foreign.vercel.app',now));
 const ceremony=await store.beginOwnerPasskey(origin,now+1);
 await assert.rejects(store.finishOwnerPasskey(origin,ceremony.challengeId,foreign.assert(ceremony.options,{credentialId:stored.id,handle:stored.userHandle}),now+2));
 await assert.rejects(store.finishOwnerPasskey(origin,ceremony.challengeId,authenticator.assert(ceremony.options,{uv:false}),now+3));
 assert.equal((await root.collection('sessions').get()).size,0);
 const answer=authenticator.assert(ceremony.options);
 const other=createCidChatEmulatorStore(tagId,'a'.repeat(32));
 await assert.rejects(other.finishOwnerPasskey(origin,ceremony.challengeId,answer,now+4));
 const session=await store.finishOwnerPasskey(origin,ceremony.challengeId,answer,now+4);
 assert.equal((await store.read(session,now+5)).role,'owner');
 assert.equal((await db.collection('users').doc(ownerId).get()).exists,false);
 await assert.rejects(store.finishOwnerPasskey(origin,ceremony.challengeId,answer,now+5));
 assert.equal((await root.collection('sessions').get()).size,1);
 const sessionDoc=(await root.collection('sessions').doc(session.id).get()).data()!;
 assert.equal(sessionDoc.ownerCredentialId,stored.id);
 assert.ok(!JSON.stringify(sessionDoc).includes(session.secret));
 await liveTag.update({blocked:true,enabled:false});
 await assert.rejects(store.read(session,now+6));
 await assert.rejects(store.beginOwnerPasskey(origin,now+6));
 await liveTag.update({blocked:false,enabled:true});
 await index(stored.id).update({revokedAt:new Date(now+7).toISOString()});
 await assert.rejects(store.read(session,now+7));
 await assert.rejects(store.beginOwnerPasskey(origin,now+7));
});
